"""Crane branch K reported against the fluids correlation at the reported split (M4 review).

Random networks (tests/unit/data/review, generated by the M4 traceability review) where
neighbouring valve and pump status changes moved a Crane tee's or wye's split back and forth
across q = 0.4-0.6. The solver held K at the mean of two values and reported it as a step of the
correlation, up to 36% off the fluids value, although the correlation has no step there for that
β and angle (rich1404, rich915) or the split ended at q = 1, far from the step (rich1090). Every
reported Crane K must be the fluids value at the reported split, to the outer loop's K_TOL.
"""

import json
from pathlib import Path

import fluids.fittings as ff
import pytest

from opensolve_pipe.models.components import TeeBranch, WyeBranch
from opensolve_pipe.models.project import Project
from opensolve_pipe.services.fluids import fluid_properties
from opensolve_pipe.services.solver import solve_project
from opensolve_pipe.services.solver.builder import build_network
from opensolve_pipe.services.solver.status import K_TOL

DATA = Path(__file__).parent / "data" / "review"


@pytest.mark.parametrize("name", ["rich1404", "rich915", "rich1090"])
def test_reported_crane_k_is_the_fluids_value_at_the_reported_split(name: str) -> None:
    project = Project.model_validate(json.loads((DATA / f"{name}.json").read_text()))
    built = build_network(project, fluid_properties(project.fluid))
    state = solve_project(project)
    assert state.converged
    checked = 0
    for comp in project.components:
        if not isinstance(comp, TeeBranch | WyeBranch) or comp.loss_model != "crane":
            continue
        result = state.branch_results.get(comp.id)
        if result is None or result.combined_port_id is None:
            continue
        geometry = built.branches[comp.id]
        combined = result.combined_port_id
        if combined not in geometry.run_ports:
            continue  # Darby fallback
        assert "held at the mean" not in result.correlation, comp.id
        assert not any(
            f.code == "CORRELATION_OUT_OF_RANGE"
            and f.component_id == comp.id
            and "step" in f.message
            for f in state.flags
        )
        run = next(p for p in geometry.run_ports if p != combined)
        branch = geometry.branch_port
        sign = -1.0 if result.pattern.startswith("diverging") else 1.0
        kind = "diverging" if sign < 0 else "converging"
        q_run = max(sign * result.port_flows[run], 0.0)
        q_branch = max(sign * result.port_flows[branch], 0.0)
        d_run, d_branch = geometry.diameter[combined], geometry.diameter[branch]
        k_branch = getattr(ff, f"K_branch_{kind}_Crane")(
            d_run, d_branch, q_run, q_branch, geometry.angle
        )
        k_run = getattr(ff, f"K_run_{kind}_Crane")(d_run, d_branch, q_run, q_branch, geometry.angle)
        assert result.k_factors[branch] == pytest.approx(k_branch, abs=K_TOL), comp.id
        assert result.k_factors[run] == pytest.approx(k_run, abs=K_TOL), comp.id
        checked += 1
    assert checked
