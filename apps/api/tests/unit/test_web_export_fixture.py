@cache
def workbook() -> openpyxl.Workbook:
    # The full load (not read_only): it parses and checks the styles part too (§7.2).
    return openpyxl.load_workbook(_wait_for(WORKBOOK))


@cache
def parts() -> dict[str, bytes]:
    with zipfile.ZipFile(_wait_for(WORKBOOK)) as archive:
        return {info.filename: archive.read(info) for info in archive.infolist()}


def xml(part: str) -> ElementTree.Element:
    return ElementTree.fromstring(parts()[part])


def find(root: ElementTree.Element, path: str) -> ElementTree.Element:
    found = root.find(path, NS)
    assert found is not None, path
    return found


@cache
def fixture_input() -> dict[str, Any]:
    data = json.loads(_wait_for(INPUT).read_text(encoding="utf-8"))
    for case in data["cases"]:
        if case["name"] == FIXTURE_CASE:
            result: dict[str, Any] = case["input"]
            return result
    raise AssertionError(f"{INPUT} has no {FIXTURE_CASE!r} case")


@cache
def sheet_parts() -> dict[str, str]:
    """Sheet name -> its part, from workbook.xml and its relationships."""
    rels = {
        r.get("Id"): r.get("Target")
        for r in xml("xl/_rels/workbook.xml.rels").findall("rel:Relationship", NS)
    }
    out = {}
    for sheet in xml("xl/workbook.xml").findall("m:sheets/m:sheet", NS):
        target = rels[sheet.get(f"{{{NS['r']}}}id")]
        out[sheet.get("name")] = target.lstrip("/") if target.startswith("/") else f"xl/{target}"
    return out


def _string_text(si: ElementTree.Element) -> str:
    """A shared string's text: its t, or its runs' t, without phonetic runs."""
    texts = [t.text or "" for t in si.findall("m:t", NS)]
    texts += [t.text or "" for t in si.findall("m:r/m:t", NS)]
    return "".join(texts)


@cache
def shared_strings_raw() -> list[ElementTree.Element]:
    return list(xml("xl/sharedStrings.xml").findall("m:si", NS))


def decode_xstring(text: str) -> str:
    """ECMA-376 ST_Xstring: every _xHHHH_ is the character U+HHHH (what LibreOffice and Excel
    read, R3), so a literal _xHHHH_ must be written as _x005F_xHHHH_."""
    return re.sub(r"_x([0-9A-Fa-f]{4})_", lambda m: chr(int(m.group(1), 16)), text)


@cache
def raw_cells(sheet: str) -> dict[str, tuple[str | None, str | None, bool]]:
    """Cell reference -> (t attribute, <v> text, has a formula), read from the sheet's XML."""
    root = xml(sheet_parts()[sheet])
    out = {}
    for c in root.iter(f"{{{NS['m']}}}c"):
        v = c.find("m:v", NS)
        out[c.get("r")] = (c.get("t"), None if v is None else v.text, c.find("m:f", NS) is not None)
    return out


def data_rows(ws: Worksheet) -> list[tuple[Any, ...]]:
    width = len(header(ws))
    return [
        tuple(c.value for c in row[:width])
        for row in ws.iter_rows(min_row=4, max_row=ws.max_row, max_col=width)
    ]


def header(ws: Worksheet) -> list[Any]:
    cells = [c.value for c in ws[3]]
    while cells and cells[-1] is None:
        cells.pop()
    return cells


def written_text(value: Any) -> str:
    """A cell's text as the writer writes it (CSV and <v>, §3.1-§3.2)."""
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, int | float):
        return js_number(float(value))
    return str(value)


def column_letter(index: int) -> str:
    letters = ""
    index += 1
    while index:
        index, rem = divmod(index - 1, 26)
        letters = chr(65 + rem) + letters
    return letters


