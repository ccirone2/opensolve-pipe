def expected_flags() -> Iterator[tuple[Any, ...]]:
    order = {"invalid": 0, "warning": 1, "info": 2}
    for case in cases():
        ss = state(case)
        for f in sorted(ss["flags"], key=lambda f: order[f["severity"]]):  # stable: API order
            details = f.get("details") or {}
            seg, fit = details.get("segmentIndex"), details.get("fittingIndex")
            yield (
                *case_columns(case),
                TEXT,
                f["code"],
                TEXT,
                f["componentId"] or f["connectionId"],
                TEXT_OR_EMPTY,
                f["portId"],
                TEXT_OR_EMPTY,
                None if seg is None else int(seg) + 1,
                None if fit is None else int(fit) + 1,
                TEXT,
                f["message"],
                ("json", details),
            )


def expected_nodes() -> Iterator[tuple[Any, ...]]:
    for case in cases():
        ss, seen = state(case), set()
        for c in as_solved(case)["components"]:
            for p in c["ports"]:
                key = f"{c['id']}:{p['id']}"
                if key not in ss["nodeResults"]:
                    continue
                seen.add(key)
                n = ss["nodeResults"][key]
                yield (
                    *case_columns(case),
                    c["id"],
                    names()[c["id"]],
                    TEXT,
                    p["id"],
                    TEXT,
                    n["elevation"],
                    n["pressure"],
                    n["dynamicPressure"],
                    n["totalPressure"],
                    n["absolutePressure"],
                    n["velocity"],
                    n["hgl"],
                    n["egl"],
                    flag_codes(
                        ss,
                        lambda f, c=c, p=p: f["componentId"] == c["id"] and f["portId"] == p["id"],
                    ),
                )
        assert seen == set(ss["nodeResults"]), "a node result has no component port"


def _connections(case: dict[str, Any]) -> Iterator[tuple[dict[str, Any], dict[str, Any]]]:
    ss = state(case)
    listed = [c for c in as_solved(case)["connections"] if c["id"] in ss["linkResults"]]
    assert {c["id"] for c in listed} == set(ss["linkResults"])
    for c in listed:
        yield c, ss["linkResults"][c["id"]]


def _link_flags(ss: dict[str, Any], cid: str) -> str | None:
    return flag_codes(ss, lambda f: f["connectionId"] == cid)


