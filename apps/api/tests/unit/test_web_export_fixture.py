def _nps(pipe: dict[str, Any]) -> str:
    for material in library()["materials"]:
        if material["id"] != pipe["materialId"]:
            continue
        for schedule in material["schedules"]:
            if schedule["id"] != pipe["schedule"]:
                continue
            for size in schedule["sizes"]:
                if math.isclose(size["nominalSize"], pipe["nominalSize"], rel_tol=1e-9):
                    nps: str = size["nps"]
                    return nps
    raise AssertionError(f"no library size for {pipe}")


