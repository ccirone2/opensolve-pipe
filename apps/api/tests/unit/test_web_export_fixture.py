    assert checked == 2 * len(cases())  # the run and branch paths of T1, in every case
    branches = workbook()["Branches"]
    on = header(branches).index("K is on")
    velocity = header(branches).index(f"Combined-flow velocity {V}")
    for row in data_rows(branches):
        assert row[on] == "Combined-flow velocity"
    # The velocity K is on is the combined-flow velocity of its branch, in every case.
    by_case = {(r[0], r[4]): abs(r[velocity]) for r in data_rows(branches)}
    for row in data_rows(ws):
        if row[v_col] is not None:
            assert row[v_col] == by_case[(row[0], row[4])]


