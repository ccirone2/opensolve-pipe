class _Text:
    """Any non-empty text: a column of the app's words (labels), which this reader does not
    copy (D14: no stable vocabulary yet); the cell must still be a shared string."""

    def __init__(self, contains: tuple[str, ...] = (), optional: bool = False) -> None:
        self.contains = contains
        self.optional = optional

    def __repr__(self) -> str:
        return f"<text containing {self.contains!r}{' or empty' if self.optional else ''}>"


TEXT = _Text()
TEXT_OR_EMPTY = _Text(optional=True)


def text_with(*parts: str) -> _Text:
    return _Text(tuple(parts))


