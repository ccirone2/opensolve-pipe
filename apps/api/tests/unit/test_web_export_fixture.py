def expected_branch_ports() -> Iterator[tuple[Any, ...]]:
    for case in cases():
        for c, b in _components(case, "branchResults"):
            combined = b["combinedPortId"]
            on_velocity = b["lossModel"] != "ideal" and combined is not None
            for p in c["ports"]:
                other = p["id"] != combined
                yield (
                    *case_columns(case),
                    c["id"],
                    names()[c["id"]],
                    p["id"],
                    TEXT,
                    b["portFlows"][p["id"]],
                    p["id"] == combined,
                    b["kFactors"].get(p["id"]) if other else None,
                    abs(b["referenceVelocity"]) if other and on_velocity else None,
                    b["pathHeadLosses"].get(p["id"]) if other else None,
                )


