def test_names_from_shared_links_round_trip_as_text() -> None:
    """Third-party names (§6): _x0041_ and a CR, a formula with quotes, a leading - stay
    exactly the text entered, as text cells, never formulas and never guarded (XLSX)."""
    project = fixture_input()["project"]
    tricky = [
        c["name"]
        for c in project["components"]
        if re.search(r"_x[0-9A-Fa-f]{4}_|\r|\"", c["name"]) or c["name"][:1] in "=+-@"
    ]
    assert len(tricky) >= 3, tricky
    raw_strings = [_string_text(si) for si in shared_strings_raw()]
    for name in tricky:
        cells = [
            (sheet, cell.coordinate)
            for sheet in workbook().sheetnames
            for row in workbook()[sheet].iter_rows()
            for cell in row
            if cell.value == name
        ]
        assert cells, f"{name!r} is in no cell as written"
        for sheet, ref in cells:
            assert workbook()[sheet][ref].data_type == "s"
            t, _, formula = raw_cells(sheet)[ref]
            assert t == "s", (sheet, ref)
            assert not formula, (sheet, ref)
        # Every underscore that begins an _xHHHH_ escaped, overlapping ones included (_x0041_x0042_
        # shares one): a left-to-right ST_Xstring reader would decode the second otherwise.
        escaped = re.sub(r"_(?=x[0-9A-Fa-f]{4}_)", "_x005F_", name)
        assert escaped in raw_strings, name  # parsed: &#13; is a CR, not a newline
        assert decode_xstring(escaped) == name
    assert "'" + tricky[0] not in raw_strings  # no CSV guard in the workbook
    assert b"\r" not in parts()["xl/sharedStrings.xml"]  # a literal CR would read as LF


