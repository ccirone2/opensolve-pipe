"""An independent reader of the web export's committed workbook (docs/proposals/export.md §7.2).

``apps/web/src/lib/utils/export/fixture.test.ts`` builds ``export-results.xlsx`` with the web's
real export model and writer from the shared fixture input (``export-input.json``, generated by
``tests/fixtures/export_input.py``); its ``scenarios`` case is the committed workbook: All cases,
SI base units. Here openpyxl (an implementation of SpreadsheetML that is not ours) opens it with
its full load, and the standard library reads its parts, and every check is made against what
the design states and what the API returns, never against the web's code:

- the workbook opens; its parts, sheets, captions, headers, frozen panes, filters, print titles,
  styles and document properties are as §3.2 states;
- every number cell equals the API's own value for the same project, bit for bit, by a
  column-to-field map written from §2.6: the API's responses the fixture holds (the workbook was
  written from them), which the API gives again here, solved through it once per case, to
  round-off (the solver's last bits differ between CPUs; ``round_off_differences``);
- every branch path's K·v²/(2g) is its path head loss (decision 29, §7.1 item 13);
- every number is written as JavaScript's ``String(n)`` (§3.2), every text cell is a shared
  string that reads back as the original text (``_xHHHH_``, CR, quotes, a leading ``=`` or
  ``-``), and nothing is a formula or a hyperlink;
- About records each solve (§2.7) and its project link decodes to the exported project.

The design commits no CSV zip, so no CSV file is read here.
"""

