# --- reading the files ----------------------------------------------------------------------


def _wait_for(path: Path) -> Path:
    assert path.is_file(), (
        f"{path} is missing: `pnpm test` in apps/web writes it with UPDATE_FIXTURES=1 "
        "(utils/export/fixture.test.ts)"
    )
    return path


@cache
def workbook() -> openpyxl.Workbook:
    # The full load (not read_only): it parses and checks the styles part too.
    return openpyxl.load_workbook(_wait_for(WORKBOOK))


@cache
def fixture_input() -> dict[str, Any]:
    data = json.loads(_wait_for(INPUT).read_text(encoding="utf-8"))
    for case in data["cases"]:
        if case["name"] == FIXTURE_CASE:
            result: dict[str, Any] = case["input"]
            return result
    raise AssertionError(f"{INPUT} has no {FIXTURE_CASE!r} case")


@cache
def parts() -> dict[str, bytes]:
    with zipfile.ZipFile(_wait_for(WORKBOOK)) as archive:
        return {info.filename: archive.read(info) for info in archive.infolist()}


def xml(part: str) -> ElementTree.Element:
    return ElementTree.fromstring(parts()[part])


@cache
def sheet_parts() -> dict[str, str]:
    """Sheet name -> its part, from workbook.xml and its relationships."""
    rels = {
        r.get("Id"): r.get("Target") or ""
        for r in xml("xl/_rels/workbook.xml.rels").findall("rel:Relationship", NS)
    }
    out: dict[str, str] = {}
    for sheet in xml("xl/workbook.xml").findall("m:sheets/m:sheet", NS):
        target = rels[sheet.get(f"{{{NS['r']}}}id")]
        name = sheet.get("name") or ""
        out[name] = target.lstrip("/") if target.startswith("/") else f"xl/{target}"
    return out


def raw_cells(sheet: str) -> dict[str, tuple[str | None, str | None, bool]]:
    """Cell reference -> (t attribute, <v> text, has a formula), read from the sheet's XML."""
    root = xml(sheet_parts()[sheet])
    out = {}
    for c in root.iter(f"{{{NS['m']}}}c"):
        v = c.find("m:v", NS)
        out[c.get("r") or ""] = (
            c.get("t"),
            None if v is None else v.text,
            c.find("m:f", NS) is not None,
        )
    return out


def data_rows(ws: Worksheet) -> list[tuple[Any, ...]]:
    width = len(header(ws))
    rows = [
        tuple(c.value for c in row[:width])
        for row in ws.iter_rows(min_row=4, max_row=max(ws.max_row, 3), max_col=width)
    ]
    return [r for r in rows if any(v is not None for v in r)]


# --- the fixture's cases and groups (design §1) ---------------------------------------------


def cases() -> list[dict[str, Any]]:
    """The exported cases in case order (the base, then the scenarios): All cases, SI, linked."""
    data = fixture_input()
    assert data["options"] == {"cases": "all", "format": "xlsx", "units": "si", "link": True}
    exported: list[dict[str, Any]] = data["cases"]
    return exported


def valued(case: dict[str, Any]) -> bool:
    """Design §1: a case with values (Compare's caseResponse, then hasValues: it converged)."""
    response = case["response"]
    return response is not None and bool(response["solvedState"]["converged"])


def state(case: dict[str, Any]) -> dict[str, Any]:
    result: dict[str, Any] = case["response"]["solvedState"]
    return result


def structure(case: dict[str, Any]) -> dict[str, Any]:
    """The project as solved (the base with the scenario's values): its components' order."""
    result: dict[str, Any] = case["inputs"]
    return result


def names() -> dict[str, str]:
    """Component names of a current case: the current project's (D17)."""
    return {c["id"]: c["name"] for c in fixture_input()["project"]["components"]}


def case_columns(case: dict[str, Any]) -> tuple[Any, ...]:
    """Case id (empty for the base), Case, Solved at (verbatim), Results."""
    assert not case["stale"], "every case of this fixture is current"
    name = "Base case" if case["id"] is None else case["name"]
    return (case["id"], name, state(case)["timestamp"], "Current")


def _ready(entry: dict[str, Any] | None) -> dict[str, Any] | None:
    if entry is None or entry.get("status") != "ready":
        return None
    response: dict[str, Any] = entry["response"]
    return response


@dataclass(frozen=True)
class Group:
    """One key of a case's group maps (design §6.3's ExportGroup, as this reader derives it)."""

    key: str
    id: str
    group_state: dict[str, Any] | None
    system_state: dict[str, Any] | None

    @property
    def group(self) -> dict[str, Any] | None:
        """The ready group-curve response."""
        return _ready(self.group_state)

    @property
    def system(self) -> dict[str, Any] | None:
        """The ready group-system-curve response."""
        return _ready(self.system_state)

    @property
    def station(self) -> dict[str, Any] | None:
        """Design §1: the ready group curve, else the ready group system curve, else none."""
        return self.group or self.system


def case_groups(case: dict[str, Any]) -> list[Group]:
    """Design §1: every key of either map of a valued case, ordered by the component index of
    the first member (members no longer in the project last), then by the Group id."""
    if not valued(case):
        return []
    order = {c["id"]: i for i, c in enumerate(structure(case)["components"])}
    unknown = len(order)
    groups = []
    for key in {*case["groupCurves"], *case["groupSystemCurves"]}:
        g = Group(key, "", case["groupCurves"].get(key), case["groupSystemCurves"].get(key))
        s = g.station
        if s is not None:
            ids = list(s["station"]["memberIds"])
        else:
            ids = sorted(key.split(NUL), key=lambda i: (order.get(i, unknown), i))
        groups.append(Group(key, "+".join(ids), g.group_state, g.system_state))
    first = {g.key: g.id.split("+")[0] for g in groups}
    return sorted(groups, key=lambda g: (order.get(first[g.key], unknown), g.id))


def ready_groups(case: dict[str, Any]) -> list[Group]:
    """The groups with a station response: those the five sheets write."""
    return [g for g in case_groups(case) if g.station is not None]


def _join(ids: list[str]) -> str | None:
    """Design §2: ids joined by '; ', null when there are none."""
    return "; ".join(ids) or None


def _state_cell(status: str, entry: dict[str, Any]) -> Any:
    """Design §3.1's loading, error and cancelled rows, shared by §3.2."""
    if status == "loading":
        return "Being computed when exported"
    if status == "error":
        return f"Failed: {entry['message']}"
    if status == "cancelled":
        return "Cancelled"
    raise AssertionError(f"unknown curve state {status!r}")


def group_curve_cell(g: Group) -> Any:
    """Design §3.1, the Group curve cell of a group with a row."""
    entry = g.group_state
    if entry is None:
        return NOT_COMPUTED
    if entry["status"] == "ready":
        r = entry["response"]
        return NO_DUTY if r["duty"] is None else f"Included ({len(r['points'])} points)"
    if entry["status"] == "refused":  # only a refusal for a pressure control inside has a row
        return text_with("Not defined: ")
    return _state_cell(entry["status"], entry)


def group_system_curve_cell(g: Group) -> Any:
    """Design §3.2, the Group system curve cell of a group with a row."""
    entry = g.system_state
    if entry is None:
        group = g.group
        # Never requested for a group curve without a duty; else the card was not asked.
        return NO_DUTY if group is not None and group["duty"] is None else NOT_COMPUTED
    if entry["status"] == "ready":
        r = entry["response"]
        return NO_DUTY if r["duty"] is None else f"Included ({len(r['systemPoints'])} points)"
    if entry["status"] == "refused":
        return text_with("Not a station: ")
    return _state_cell(entry["status"], entry)


def _rise_order(points: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Design §1: group-curve points by rise (a stable sort)."""
    return sorted(points, key=lambda p: p["head"])


def _flow_order(points: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Design §1: group-system-curve points by flow (a stable sort)."""
    return sorted(points, key=lambda p: p["flow"])


def _speed(member: dict[str, Any]) -> float | None:
    """The Pumps sheet's rule (design §2.2): no speed for a pump that is off."""
    return None if member["status"] == "off" else member["speed"]


