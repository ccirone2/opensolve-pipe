def test_the_rows_marked_at_the_duty_hold_the_duty_checks_values() -> None:
    """About's claim (design §2.1, §4.1): the duty check's flows are the Group curves row marked
    At the duty rise and its members' rows; the system duty check's rise is the Group system
    curves row marked At the duty flow. Read from the workbook, against the stored responses."""
    curves, members, systems = (workbook()[s] for s in GROUP_SHEETS[2:])
    c_head, m_head, s_head = header(curves), header(members), header(systems)
    checked = 0
    for case in cases():
        for g in ready_groups(case):
            if g.group is not None and g.group["dutyCheck"] is not None:
                check = g.group["dutyCheck"]
                rows = [
                    r
                    for r in data_rows(curves)
                    if r[0] == case["id"] and r[4] == g.id and r[c_head.index("At the duty rise")]
                ]
                assert len(rows) == 1, (case["id"], g.id)
                (row,) = rows
                assert row[c_head.index(f"Station flow {Q}")] == check["flow"]
                point = row[c_head.index("Point #")]
                flows = {
                    r[m_head.index("Pump id")]: r[m_head.index(f"Flow {Q}")]
                    for r in data_rows(members)
                    if r[0] == case["id"] and r[4] == g.id and r[m_head.index("Point #")] == point
                }
                assert flows == {m["pumpId"]: m["flow"] for m in check["members"]}
                checked += 1
            if g.system is not None and g.system["systemDutyCheck"] is not None:
                rows = [
                    r
                    for r in data_rows(systems)
                    if r[0] == case["id"] and r[4] == g.id and r[s_head.index("At the duty flow")]
                ]
                assert len(rows) == 1, (case["id"], g.id)
                assert rows[0][s_head.index(f"Rise {H}")] == g.system["systemDutyCheck"]["head"]
                checked += 1
    assert checked == 3  # the base's two checks and S1's duty check


def test_the_duty_in_the_file_is_the_cases_own_solve() -> None:
    """About's sign row, read from the workbook against the stored solve, bit for bit (D21: the
    duty is the case's own solve): Rise = EGL(D) − EGL(S); Station flow is + from S into the
    station (the flows of the connections outside the station at S); each pump's flow, head
    and speed are its pump result's."""
    groups, members = workbook()["Pump groups"], workbook()["Pump group members"]
    g_head, m_head = header(groups), header(members)
    checked = 0
    for case in cases():
        ss = state(case)
        for g in ready_groups(case):
            assert g.station is not None
            station = g.station["station"]
            row = next(r for r in data_rows(groups) if r[0] == case["id"] and r[4] == g.id)
            s, d = station["inlet"], station["outlet"]
            assert s["portId"] is not None  # ports, not whole tanks
            assert d["portId"] is not None
            egl_s = ss["nodeResults"][f"{s['componentId']}:{s['portId']}"]["egl"]
            egl_d = ss["nodeResults"][f"{d['componentId']}:{d['portId']}"]["egl"]
            assert row[g_head.index(f"Rise {H}")] == egl_d - egl_s
            inside = set(station["interiorConnectionIds"])
            into = 0.0
            for c in structure(case)["connections"]:
                if c["id"] in inside:
                    continue
                flow = ss["linkResults"][c["id"]]["flow"]
                if (c["toComponentId"], c["toPortId"]) == (s["componentId"], s["portId"]):
                    into += flow
                if (c["fromComponentId"], c["fromPortId"]) == (s["componentId"], s["portId"]):
                    into -= flow
            assert row[g_head.index(f"Station flow {Q}")] == into
            for r in data_rows(members):
                if r[0] != case["id"] or r[4] != g.id:
                    continue
                pump = ss["pumpResults"][r[m_head.index("Pump id")]]
                assert r[m_head.index(f"Flow {Q}")] == pump["operatingFlow"]
                assert r[m_head.index(f"Head {H}")] == pump["operatingHead"]
                speed = r[m_head.index("Speed")]
                assert speed == (None if pump["status"] == "off" else pump["speed"])
                checked += 1
    assert checked == 4


