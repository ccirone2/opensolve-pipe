def test_the_fixture_exercises_what_this_reader_checks() -> None:
    """The premises the checks below rest on, so none of them passes vacuously."""
    data = fixture_input()
    assert [c["id"] for c in cases()] == [None, "S1"]
    assert all(c["status"] == "solved" and valued(c) and not c["stale"] for c in cases())
    base, off = cases()
    assert [len(case_groups(c)) for c in cases()] == [1, 1]
    assert [g.id for c in cases() for g in ready_groups(c)] == ["PA+PB", "PA+PB"]
    (g,) = ready_groups(base)
    assert g.group is not None
    assert g.system is not None
    assert g.group["station"]["arrangement"] == "parallel"
    (h,) = ready_groups(off)
    assert h.group is not None
    assert h.system_state is None  # the Not computed cell
    assert [m["status"] for m in h.group["duty"]["members"]] == ["running", "off"]
    reasons = [p for p in g.system["systemPoints"] if p["reason"] is not None]
    assert reasons, "points with a reason and its data"
    assert all(p["reason"] == "beyond_limit" and p["limitFlow"] is not None for p in reasons)
    assert any(p["isDuty"] for p in g.group["points"])
    assert any(p["isDuty"] for p in g.system["systemPoints"])
    assert data["goalSeek"] is None


