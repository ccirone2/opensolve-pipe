def _system_reason_words(p: dict[str, Any]) -> Any:
    """The card's note on a point (design §2.5): empty or text where the point has no reason;
    where it has one, text that tells the ids and numbers its data quote with names and display
    units (CLAUDE.md D10), here the elements' names and the flows in m³/s (an SI file writes SI
    words, design §2)."""
    if not p["reason"]:
        return TEXT_OR_EMPTY
    n = names()
    flows = ["m³/s"] if p["limitFlow"] is not None or p["passedFlow"] is not None else []
    return text_with(*[n[i] for i in p["componentIds"]], *flows)


