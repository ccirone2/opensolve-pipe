# --- (e) Methods: each group's method section after its case's -----------------------------


def _methods_block(g: Group) -> list[str]:
    """Design §5: '', 'Pumps together: {id}, {kind}', the heading, '- item' lines, then
    'References:' and '- ref' lines when there are references; the group curve first."""
    lines: list[str] = []
    for kind, r in (("group curve", g.group), ("group system curve", g.system)):
        if r is None:
            continue
        methods = r["methods"]
        lines += ["", f"Pumps together: {g.id}, {kind}"]
        lines.append(f"{methods['title']} (calculation methods {r['methodVersion']})")
        lines += [f"- {item}" for item in methods["items"]]
        if methods["references"]:
            lines += ["References:", *[f"- {ref}" for ref in methods["references"]]]
    return lines


