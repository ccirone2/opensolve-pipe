/** What a trial solve gave (§6.9): Yes, or why it gave no usable result. */
export function outcomeLabel(evaluation: Pick<GoalSeekEvaluation, 'outcome' | 'message'>): string {
	switch (evaluation.outcome) {
		case 'usable':
			return 'Yes';
		case 'not_converged':
			return 'Did not converge';
		case 'no_value':
			return `No value: ${evaluation.message}`;
		case 'topology_error':
		case 'fluid_error':
			return `Rejected: ${evaluation.message}`;
		case 'not_computed':
			return 'Not computed (time budget)';
		default:
			return evaluation.message || evaluation.outcome;
	}
}

