export const GOAL_SEEK_BUDGET_S = 45;

/** What the page is calculating: one request at a time (D10; proposal §6.8). */
export type Calculating = 'solve' | 'solveAll' | 'goalSeek' | null;

/**
 * Why a control that starts `starting` is unavailable while `calculating` runs ('' when it is
 * available). Every Solve, Solve all, Solve again and Solve now control and Run goal seek take
 * their reason here, from the store's one `calculating` getter, so a new entry point cannot miss
 * a goal seek. `header`: the control sits beside the header's Cancel.
 */
export function calculatingReason(
	calculating: Calculating,
	starting: 'solve' | 'goalSeek' | 'export',
	header = false
): string {
	if (calculating === null) return '';
	if (starting === 'export') {
		// Export makes no request, but never from results about to be replaced (export.md §5.2).
		const running =
			calculating === 'goalSeek'
				? 'A goal seek is running'
				: calculating === 'solveAll'
					? 'Solve all is running'
					: 'A solve is running';
		return `${running}; export when it finishes, or ${header ? 'Cancel' : 'Cancel in the header'} stops it.`;
	}
	if (starting === 'goalSeek') {
		return calculating === 'goalSeek'
			? 'A goal seek is running; Cancel stops it.'
			: 'A solve is running; wait for it or cancel it.';
	}
	const cancel = header ? 'Cancel stops it.' : 'Cancel in the header stops it.';
	if (calculating === 'goalSeek') return `A goal seek is running; ${cancel}`;
	return calculating === 'solveAll'
		? `Solve all is running; ${cancel}`
		: `A solve is running; ${cancel}`;
}

