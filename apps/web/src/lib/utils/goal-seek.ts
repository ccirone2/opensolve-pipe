/** A goal as the request sends it (stable key order; the tolerance only when entered). */
export function requestGoal(goal: GoalDraft): Goal {
	if (goal.target === null) throw new Error('A goal without a target cannot be sent.');
	return {
		quantity: goal.quantity,
		elementId: goal.elementId,
		...(goal.portId ? { portId: goal.portId } : {}),
		target: goal.target,
		...(goal.tolerance === null ? {} : { tolerance: goal.tolerance })
	};
}

/** A variable as the request sends it (stable key order). */
export function requestVariable(
	variable: Pick<VariableDraft, 'target' | 'field' | 'coefficient' | 'lower' | 'upper'>
): GoalVariable {
	const { target, lower, upper } = variable;
	if (target.kind === 'component') {
		return {
			kind: 'component',
			componentId: target.componentId,
			field: variable.field as Extract<GoalVariable, { kind: 'component' }>['field'],
			...(variable.coefficient ? { coefficient: variable.coefficient } : {}),
			lower,
			upper
		};
	}
	if (target.kind === 'pipe') {
		return {
			kind: 'pipe',
			connectionId: target.connectionId,
			pipeIndex: target.pipeIndex,
			field: 'length',
			lower,
			upper
		};
	}
	return { kind: 'project', field: 'fluid.temperature', lower, upper };
}

/** Whether two items of a request list are the same by `x-goal-seek-rules` (absent keys null). */
function sameBy(list: 'variables' | 'goals', a: object, b: object): boolean {
	const keys = goalSeekLimits().uniqueBy[list] ?? [];
	const record = (x: object) => x as Record<string, unknown>;
	return keys.every((key) => (record(a)[key] ?? null) === (record(b)[key] ?? null));
}

/** A goal's identity as a request item (what `x-goal-seek-rules` compares). */
function goalItem(goal: GoalRef) {
	return { quantity: goal.quantity, elementId: goal.elementId, portId: goal.portId ?? null };
}

/** Whether a goal like `goal` is in the setup already ("(already a goal)"). */
export function hasGoal(setup: GoalSeekSetup, goal: GoalRef): boolean {
	return setup.goals.some((g) => sameBy('goals', goalItem(g), goalItem(goal)));
}

/** Whether a variable like `choice` is in the setup already ("(already a variable)"). */
export function hasVariable(
	setup: GoalSeekSetup,
	choice: Pick<VariableDraft, 'target' | 'field'>
): boolean {
	const item = requestVariable({ ...choice, lower: 0, upper: 1 });
	return setup.variables.some((v) => sameBy('variables', requestVariable(v), item));
}

/** A row's identity in the setup (rows are unique by it, as the request's items). */
export function goalKey(goal: GoalRef): string {
	return [goal.quantity, goal.elementId, goal.portId ?? ''].join('\u0000');
}

export function variableKey(variable: Pick<VariableDraft, 'target' | 'field'>): string {
	return `${targetKey(variable.target)}\u0000${variable.field}`;
}

/** Why a goal no longer applies in `project` (deleted element or port), or null. */
export function goalLapse(project: Project, goal: GoalDraft): string | null {
	const group = goalGroup(goal.quantity);
	if (group === 'connection') {
		return connectionById(project, goal.elementId)
			? null
			: `${goal.elementId} (deleted): no longer exists`;
	}
	const component = componentById(project, goal.elementId);
	if (!component) return `${goal.elementId} (deleted): no longer exists`;
	if (goal.portId && !component.ports.some((p) => p.id === goal.portId)) {
		return `${portLabel(goal.portId)} of ${component.name} (deleted): no longer exists`;
	}
	return null;
}

/**
 * Why a variable no longer applies in the case shown `project` (§6.5), or null: its element is
 * deleted; the value is not there (flow control removed, the fluid made custom, a valve no longer
 * a control valve); a pipe variable's connection has other pipes or ends than when chosen (page
 * state cannot follow pipes as scenario changes do); a setpoint's valve changed type (a pressure
 * became a flow).
 */
export function variableLapse(project: Project, variable: VariableDraft): string | null {
	const { target } = variable;
	if (target.kind === 'pipe') {
		const now = pipesRecord(project, target.connectionId);
		if (!now) return `${target.connectionId} (deleted): no longer exists`;
		if (
			variable.pipes &&
			(now.count !== variable.pipes.count || now.ends !== variable.pipes.ends)
		) {
			return `The pipes of ${connectionName(project, target.connectionId)} changed since you chose Pipe ${target.pipeIndex + 1}; choose it again.`;
		}
		return target.pipeIndex < now.count
			? null
			: `${target.connectionId} has no pipe ${target.pipeIndex + 1}`;
	}
	if (target.kind === 'project') {
		return valueOf(project, target, variable.field) === undefined
			? 'the fluid is a custom fluid'
			: null;
	}
	const component = componentById(project, target.componentId);
	if (!component) return `${target.componentId} (deleted): no longer exists`;
	if (
		!variableField(project, target, variable.field) ||
		valueOf(project, target, variable.field) === undefined
	) {
		return variable.field === 'control.setpoint'
			? `${component.name} has no flow control`
			: `${component.name} has no ${fieldLabelFor(component, variable.field).toLowerCase()}`;
	}
	if (
		variable.valveType &&
		component.type === 'valve' &&
		component.valveType !== variable.valveType
	) {
		return `${component.name} changed type since you chose its setpoint; choose it again`;
	}
	return null;
}

/** The ids of components and connections the setup names: no new element takes them (§6.15). */
export function reservedIds(setup: GoalSeekSetup): string[] {
	const ids = new Set<string>();
	for (const g of setup.goals) ids.add(g.elementId);
	for (const v of setup.variables) {
		if (v.target.kind === 'component') ids.add(v.target.componentId);
		if (v.target.kind === 'pipe') ids.add(v.target.connectionId);
	}
	return [...ids];
}

/**
 * Why Run is unavailable, every reason in order (§6.8; the first is shown). `project` is the case
 * shown. The counts and the bounds' order are the published rules (`x-goal-seek-rules`, the
 * variable schemas' `x-ordered-fields`).
 */
export function runProblems(
	setup: GoalSeekSetup,
	project: Project,
	calculating: Calculating,
	prefs: UnitPreferences
): string[] {
	const problems: string[] = [];
	const { goals, variables } = setup;
	if (!project.components.length) problems.push('Add a component to the network first.');
	if (!goals.length || !variables.length) problems.push('Add at least one goal and one variable.');
	const lists = { variables: variables.length, goals: goals.length };
	for (const [a, b] of goalSeekLimits().sameLength) {
		const n = lists[a as keyof typeof lists];
		const m = lists[b as keyof typeof lists];
		if (n && m && n !== m) {
			problems.push(
				`Goal seek needs as many goals as variables: ${lists.goals} goal${lists.goals === 1 ? '' : 's'}, ${lists.variables} variable${lists.variables === 1 ? '' : 's'}.`
			);
		}
	}
	if (goals.some((g) => g.target === null)) problems.push('Enter a target for each goal.');
	if (goals.some((g) => toleranceProblem(g, prefs))) {
		problems.push('A tolerance is below the smallest for its target; see the goals.');
	}
	if (
		goals.some((g) => goalLapse(project, g)) ||
		variables.some((v) => variableLapse(project, v))
	) {
		problems.push('Remove the goals and variables that no longer apply.');
	}
	if (variables.some((v) => !boundsInOrder(v))) {
		problems.push('Each variable needs its From value below its To value.');
	}
	const busy = calculatingReason(calculating, 'goalSeek');
	if (busy) problems.push(busy);
	return problems;
}

/**
 * The request for the setup on case `caseId` of the stored project `project` (base and scenarios,
 * as Solve sends it): SI values, the scenario's id only for a scenario, nothing else.
 */
export function toRequest(setup: GoalSeekSetup, project: Project, caseId: CaseId): GoalSeekRequest {
	return {
		project,
		...(caseId === null ? {} : { scenarioId: caseId }),
		variables: setup.variables.map(requestVariable),
		goals: setup.goals.map(requestGoal)
	};
}

/** The setup a request was made from, for labelling a result (variables and goals as sent). */
export function draftsOf(request: GoalSeekRequest): {
	variables: VariableDraft[];
	goals: GoalDraft[];
} {
	return {
		variables: request.variables.map((v) => {
			const target: ChangeTarget =
				v.kind === 'component'
					? { kind: 'component', componentId: v.componentId }
					: v.kind === 'pipe'
						? { kind: 'pipe', connectionId: v.connectionId, pipeIndex: v.pipeIndex }
						: { kind: 'project' };
			return {
				target,
				field: v.field,
				...(v.kind === 'component' && v.coefficient ? { coefficient: v.coefficient } : {}),
				lower: v.lower,
				upper: v.upper,
				defaults: { lower: v.lower, upper: v.upper }
			};
		}),
		goals: request.goals.map((g) => ({
			quantity: g.quantity,
			elementId: g.elementId,
			...(g.portId ? { portId: g.portId } : {}),
			target: g.target,
			tolerance: g.tolerance ?? null
		}))
	};
}

