/** The smallest tolerance a goal may have (SI): max(relative × |target|, absolute), published. */
export function minimumTolerance(quantity: GoalQuantity, target: number | null): number {
	const { relative, absolute } = rule(quantity).minimum;
	return Math.max(relative * Math.abs(target ?? 0), absolute);
}

/** Bounds of a goal's target: the schema's. */
export function targetBounds(): Bounds {
	return schemaBounds('Goal', 'target');
}

/**
 * Bounds of a goal's tolerance: the schema's (> 0), and at least the quantity's minimum for the
 * target (`x-goal-quantities`), which moves with the target: so a tolerance the field accepts is
 * never one the API rejects.
 */
export function toleranceBounds(quantity: GoalQuantity, target: number | null): Bounds {
	return intersectBounds(schemaBounds('Goal', 'tolerance'), {
		minimum: minimumTolerance(quantity, target)
	});
}

/** Why a goal's entered tolerance is below its minimum now (the target moved), or null. */
export function toleranceProblem(goal: GoalDraft, prefs: UnitPreferences): string | null {
	if (goal.tolerance === null) return null;
	const minimum = minimumTolerance(goal.quantity, goal.target);
	if (goal.tolerance >= minimum) return null;
	const spec = goalSpec(goal.quantity);
	return `Below the smallest tolerance for this target: at least ${formatValue(minimum, spec.category, prefs, 6)}.`;
}

/**
 * The default tolerance in words, from `x-goal-quantities`: "Default tolerance: 0.5 % of the
 * target, at least 0.001 L/s" (a pressure's floor is a head: "at least 0.01 m of head").
 */
export function defaultToleranceText(quantity: GoalQuantity, prefs: UnitPreferences): string {
	const { relativeTolerance, floor } = rule(quantity);
	const relative = `${formatNumber(relativeTolerance * 100, 4)} % of the target`;
	const spec = goalSpec(quantity);
	let least = '';
	if (floor.head !== undefined) {
		least =
			spec.category === 'pressure'
				? `${formatValue(floor.head, 'head', prefs)} of head`
				: formatValue(floor.head, 'head', prefs);
	} else if (floor.flow !== undefined) least = formatValue(floor.flow, 'flow', prefs);
	else if (floor.velocity !== undefined) least = formatValue(floor.velocity, 'velocity', prefs);
	return `Default tolerance: ${relative}${least ? `, at least ${least}` : ''}.`;
}

