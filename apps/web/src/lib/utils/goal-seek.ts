/** The overrides a response applies: each variable's (none when no value was found). */
export function foundOverrides(response: GoalSeekResponse | null): Override[] {
	if (!response) return [];
	return response.result.variables.flatMap((v) => (v.override ? [v.override as Override] : []));
}

/** A target of an override (component, pipe or project). */
function targetOf(o: Override): ChangeTarget {
	return o.kind === 'component'
		? { kind: 'component', componentId: o.componentId }
		: o.kind === 'pipe'
			? { kind: 'pipe', connectionId: o.connectionId, pipeIndex: o.pipeIndex }
			: { kind: 'project' };
}

/**
 * The scenario's changes with the values found upserted (by target and field, withChange); a
 * value exactly equal to the base's removes the change instead (D15 decision 21). A whole-fluid
 * override replaces the scenario's fluid change.
 */
function upserted(
	base: Project,
	overrides: readonly Override[],
	list: readonly Override[]
): Override[] {
	let scenario: Scenario = { id: '', name: '', overrides: [...list] };
	for (const o of overrides) {
		const target = targetOf(o);
		const baseValue =
			o.kind === 'project' && o.field === 'fluid' ? base.fluid : valueOf(base, target, o.field);
		scenario = sameValue(o.value, baseValue)
			? withoutChange(scenario, target, o.field)
			: withChange(scenario, o);
	}
	return [...overridesOf(scenario)];
}

/**
 * The project with the values found applied to the case they ran on (§6.10): written into the
 * base at their paths (setValue), or upserted into scenario `caseId`. Exact floats: never a
 * displayed text. Returns a new project, its pipes recorded as the same pipes (identity.ts), so
 * Build still reads the last solve on them while it is out of date.
 */
export function applyToCase(
	project: Project,
	caseId: CaseId,
	overrides: readonly Override[]
): Project {
	const draft = structuredClone(project) as Project;
	markProjectCopy(draft, project);
	if (caseId === null) {
		for (const o of overrides) {
			if (o.kind === 'project' && o.field === 'fluid')
				draft.fluid = structuredClone(o.value) as Project['fluid'];
			else setValue(draft, targetOf(o), o.field, o.value);
		}
		return draft;
	}
	const scenario = draft.scenarios?.find((s) => s.id === caseId);
	if (scenario) scenario.overrides = upserted(project, overrides, overridesOf(scenario));
	return draft;
}

/** The number in a new scenario's name: its id's ("S3" → 3). */
function scenarioNumber(project: Project, id: string): number {
	const n = /^S(\d+)$/.exec(id)?.[1];
	return n ? Number(n) : (project.scenarios?.length ?? 0) + 1;
}

/** "text…", cut to `limit` characters. */
function cut(text: string, limit: number): string {
	return text.length <= limit ? text : `${text.slice(0, limit - 1)}…`;
}

/**
 * "Values found by goal seek on the base case for: Transfer pump → Discharge valve · Flow 15 L/s
 * (met). 2026-10-25." In display units at that time, cut to the description limit.
 */
export function newScenarioDescription(
	response: GoalSeekResponse,
	request: GoalSeekRequest,
	context: WordsContext,
	date: string
): string {
	const views = runViews(context, request);
	const goals = response.result.goals
		.map((g) => {
			const view = views.goals[g.index] as GoalView;
			return `${view.label} ${view.target((request.goals[g.index] as Goal).target)} (${g.met ? 'met' : 'not met'})`;
		})
		.join('; ');
	return cut(
		`Values found by goal seek on ${context.caseWords} for: ${goals}. ${date}.`,
		SCENARIO_DESCRIPTION_LIMIT
	);
}

/**
 * The project with a new scenario holding the run case's changes (none for the base; copied as
 * Duplicate does) and the values found upserted, the same equal-to-base rule. Its id is the next
 * free one, its name "Goal seek {n}" from the id's number.
 */
export function asNewScenario(
	project: Project,
	caseId: CaseId,
	overrides: readonly Override[],
	description: string
): { project: Project; id: string; name: string } {
	const id = newScenarioId(project);
	const name = `Goal seek ${scenarioNumber(project, id)}`;
	const own = structuredClone([...overridesOf(findScenario(project, caseId))]);
	const scenario = { id, name, description, overrides: upserted(project, overrides, own) };
	return {
		project: withScenarios(project, [...(project.scenarios ?? []), scenario]),
		id,
		name
	};
}

/** How many changes applying would leave the scenario with, and how many it adds. */
function changeCount(project: Project, caseId: CaseId, overrides: readonly Override[]) {
	const own = overridesOf(findScenario(project, caseId));
	const next = upserted(project, overrides, own);
	return { now: own.length, next: next.length, added: Math.max(0, next.length - own.length) };
}

/**
 * Why a result's values cannot be applied in `mode` now (§6.10), or null: no values, out of date,
 * more changes than a scenario holds, more scenarios than a project holds. A scenario run is never
 * applied to the base: Apply to case applies to the case it ran on.
 */
export function applyProblems(
	project: Project,
	state: { caseId: CaseId; response: GoalSeekResponse | null; stale: boolean },
	mode: 'case' | 'new',
	caseName: (caseId: CaseId) => string
): string | null {
	const overrides = foundOverrides(state.response);
	if (!overrides.length) return 'There are no values to apply.';
	if (state.stale) {
		return 'Out of date: the project changed after this goal seek. Run it again to apply values that hold.';
	}
	if (mode === 'new' && (project.scenarios?.length ?? 0) >= MAX_SCENARIOS) {
		return `A project holds at most ${MAX_SCENARIOS} scenarios.`;
	}
	if (mode === 'case' && state.caseId !== null && !findScenario(project, state.caseId)) {
		return `${caseName(state.caseId)} no longer exists.`;
	}
	if (mode === 'case' && state.caseId === null) return null;
	const count = changeCount(project, state.caseId, overrides);
	if (count.next > MAX_CHANGES) {
		const name = mode === 'case' ? caseName(state.caseId) : 'The new scenario';
		return mode === 'case'
			? `${name} holds ${count.now} changes; these values would add ${count.added}, more than the ${MAX_CHANGES} a scenario holds. Remove a change first.`
			: `${name} would hold ${count.next} changes, more than the ${MAX_CHANGES} a scenario holds.`;
	}
	return null;
}

/**
 * The scenarios that set their own value of an applied base value (they keep it): a change of its
 * field, of a whole value it is a part of (an equipment item's whole rating keeps its own rated
 * pressure drop), or of a part of it (the whole fluid applied: a scenario's own temperature).
 */
export function keptByScenarios(
	project: Project,
	overrides: readonly Override[]
): { label: string; scenarios: string[] }[] {
	const kept: { label: string; scenarios: string[] }[] = [];
	for (const o of overrides) {
		const target = targetOf(o);
		const entries =
			target.kind === 'project'
				? projectOverrideFields()
				: target.kind === 'pipe'
					? pipeOverrideFields()
					: componentOverrideFields(componentById(project, target.componentId) ?? {});
		const fields = [...valueAndWholes(o.field), ...partsOf(entries, o.field)];
		const names = (project.scenarios ?? [])
			.filter((s) => fields.some((f) => findChange(s, target, f)))
			.map((s) => s.name);
		if (names.length) kept.push({ label: variableLabelOf(project, o), scenarios: names });
	}
	return kept;
}

function coefficientOfOverride(o: Override): Coefficient | undefined {
	if (o.field !== 'resistance' || !o.value || typeof o.value !== 'object') return undefined;
	return (o.value as { kind?: Coefficient }).kind;
}

/** "Transfer pump speed", "Pipe 2 of A → B length", "fluid temperature": for a notice. */
export function variableLabelOf(project: Project, o: Override): string {
	const coefficient = coefficientOfOverride(o);
	return variableNoticeLabel(project, {
		target: targetOf(o),
		field: o.field === 'fluid' ? 'fluid.temperature' : o.field,
		...(coefficient ? { coefficient } : {})
	});
}

/** A variable named for a notice: "Transfer pump speed", "fluid temperature", "Strainer Cv". */
function variableNoticeLabel(
	project: Project,
	draft: Pick<VariableDraft, 'target' | 'field' | 'coefficient' | 'ratingKind'>
): string {
	const label = variableFieldLabel(project, draft).replace(/ \(.*\)$/, '');
	// A Cv, Kv or K keeps its symbol's case ("Strainer Cv", "valve resistance Cv"); every other
	// label is lowercase in a sentence.
	const field =
		label === 'Cv' || label === 'Kv'
			? label
			: draft.field === 'resistance'
				? `resistance ${draft.coefficient ?? 'K'}`
				: label.toLowerCase();
	if (draft.target.kind === 'project') return field;
	return `${changeTargetLabel(project, makeOverride(draft.target, draft.field, null))} ${field}`;
}

/**
 * Each value a response found, for a notice (the dialog's outcome announcement, Apply's notice and
 * its "already holds" text): "Transfer pump speed 86.1174 %", one per variable with a value, its
 * label and value from the variable itself (§6.4 of equipment-pressure-drop.md), never from its
 * override: an override may be a whole value (a scenario's whole rating or fluid) holding other
 * values too, the same for two variables. Names from `labels`; the case's words from `context`.
 */
export function foundValueTexts(
	response: GoalSeekResponse | null,
	context: Pick<WordsContext, 'labels' | 'sent' | 'prefs' | 'caseId'>
): string[] {
	if (!response) return [];
	const words: WordsContext = { ...context, caseWords: '' };
	return response.result.variables.flatMap((result) => {
		if (result.value === null || result.value === undefined) return [];
		const view = variableView(words, result.variable);
		const [draft] = draftsOf({
			project: context.sent,
			variables: [result.variable],
			goals: []
		}).variables;
		const v = draft as VariableDraft;
		const ratingKind = v.field === 'rating.value' ? caseRatingKind(words, v.target) : undefined;
		const label = variableNoticeLabel(context.labels, ratingKind ? { ...v, ratingKind } : v);
		// A Cv, Kv or K is named by its kind in the label ("Strainer Cv", "valve resistance Cv"):
		// its number goes without the "Cv " a view prefixes, never "Strainer Cv Cv 81.0724".
		const text =
			v.field === 'rating.value' || v.field === 'resistance'
				? variableText(
						result.value,
						{ category: view.spec.category, options: view.spec.options },
						context.prefs
					)
				: view.text(result.value);
		return [`${label} ${text}`];
	});
}

