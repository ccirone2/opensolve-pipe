/**
 * What the words of a result need: the project for names (always current names; an element
 * deleted since is named from the project as sent), the case as sent (a setpoint's unit), the
 * display units and the case in words ("the base case", "scenario Winter"). A connection of an
 * out-of-date result (`stale`) is named from the project as sent, as the Links table names one
 * (utils/results.ts resultsProject): its goal's flow and head loss are signed by those ends, and a
 * pipe variable's number is its place in that order.
 */
export interface WordsContext {
	labels: Project;
	sent: Project;
	prefs: UnitPreferences;
	caseWords: string;
	/** The result is out of date (the project changed since the run). */
	stale?: boolean;
	/**
	 * The case the run was on (null or absent: the base), whose values some words depend on: an
	 * equipment item's Cv or Kv is named by its kind in that case (a scenario may rate it otherwise).
	 */
	caseId?: CaseId;
}

/** The kind of an equipment item's coefficient in the case of `context` (rating.value's words). */
function caseRatingKind(
	context: WordsContext,
	target: ChangeTarget
): RatedFlowCoefficient['kind'] | undefined {
	if (target.kind !== 'component') return undefined;
	const project = context.caseId ? caseProject(context.sent, context.caseId) : context.sent;
	const component = componentById(project, target.componentId);
	return component?.type === 'equipment' && component.rating.kind !== 'point'
		? component.rating.kind
		: undefined;
}

const MINUS = '−';

function signedText(text: string, value: number): string {
	if (value === 0 || /^0(\s|$)/.test(text)) return text;
	return value > 0 ? `+${text}` : `${MINUS}${text.replace(/^-/, '')}`;
}

/**
 * The project that names an element: the current one, else the one sent (deleted since); for a
 * connection of an out-of-date result, the one sent (its ends as run).
 */
function namesProject(context: WordsContext, id: string): Project {
	if (connectionById(context.labels, id)) return context.stale ? context.sent : context.labels;
	return componentById(context.labels, id) ? context.labels : context.sent;
}

/** A variable of a run, named and shown in display units. */
export interface VariableView {
	label: string;
	spec: ValueSpec;
	/** "86.1174 %", "Cv 18.2346". */
	text: (x: number) => string;
	/** "a and b" of a range or bracket, with the digits that tell them apart (`pairText`). */
	pair: (a: number, b: number) => [string, string];
	/** The unit's label, for a table heading ('%', 'L/s'; '' for a coefficient). */
	unit: string;
}

export function variableView(context: WordsContext, variable: GoalVariable): VariableView {
	const [draft] = draftsOf({ project: context.sent, variables: [variable], goals: [] }).variables;
	const found = draft as VariableDraft;
	const ratingKind =
		found.field === 'rating.value' ? caseRatingKind(context, found.target) : undefined;
	const v: VariableDraft = ratingKind ? { ...found, ratingKind } : found;
	const id =
		v.target.kind === 'component'
			? v.target.componentId
			: v.target.kind === 'pipe'
				? v.target.connectionId
				: '';
	const project = id ? namesProject(context, id) : context.labels;
	const spec = variableSpec(context.sent, v);
	const f = new Formatter(context.prefs);
	return {
		label: variableLabel(project, v),
		spec,
		text: (x) => variableText(x, spec, context.prefs),
		pair: (a, b) => pairText(a, b, spec, context.prefs),
		unit:
			spec.category === 'dimensionless'
				? (v.coefficient ?? v.ratingKind ?? '')
				: f.unit(spec.category, spec.options)
	};
}

const SUPERSCRIPT: Readonly<Record<string, string>> = {
	'-': '⁻',
	'0': '⁰',
	'1': '¹',
	'2': '²',
	'3': '³',
	'4': '⁴',
	'5': '⁵',
	'6': '⁶',
	'7': '⁷',
	'8': '⁸',
	'9': '⁹'
};

/**
 * A magnitude to `sig` significant digits in plain decimals ("0.0000069"), or as 6.9×10⁻⁸ when
 * smaller than 10⁻⁶ or from 10⁹: the "Off by" of a goal, whose digits matter when it is small.
 */
export function differenceText(magnitude: number, sig = 2): string {
	if (!Number.isFinite(magnitude)) return '—';
	if (magnitude === 0) return '0';
	const rounded = Number(Math.abs(magnitude).toPrecision(sig));
	if (rounded >= 1e-6 && rounded < 1e9) {
		const decimals = Math.max(0, sig - 1 - Math.floor(Math.log10(rounded)));
		return rounded
			.toFixed(decimals)
			.replace(/(\.\d*?)0+$/, '$1')
			.replace(/\.$/, '');
	}
	const [mantissa = '', exponent = ''] = rounded.toExponential(sig - 1).split('e');
	const digits = mantissa.includes('.') ? mantissa.replace(/\.?0+$/, '') : mantissa;
	const power = exponent.replace('+', '');
	return `${digits}×10${[...power].map((c) => SUPERSCRIPT[c] ?? c).join('')}`;
}

/** A goal of a run, named and shown in display units. */
export interface GoalView {
	label: string;
	spec: ValueSpec;
	/** A value reached, at the results tables' precision ("15.00 L/s"). */
	value: (g: number) => string;
	/** A target as entered (6 significant digits). */
	target: (t: number) => string;
	/** A difference: signed, with a true minus, 2 significant digits ("+0.0000069 L/s"). */
	offBy: (r: number) => string;
	/** A tolerance: "±0.075 L/s". */
	tolerance: (tol: number) => string;
	unit: string;
}

export function goalView(context: WordsContext, goal: Goal): GoalView {
	const spec = goalSpec(goal.quantity);
	const f = new Formatter(context.prefs);
	const prefs = context.prefs;
	return {
		label: goalLabel(namesProject(context, goal.elementId), goal),
		spec,
		value: (g) => f.value(g, spec.category, spec.options),
		target: (t) => formatValue(t, spec.category, prefs, 6, spec.options),
		offBy: (r) => {
			const unit = f.unit(spec.category, spec.options.gauge ? {} : spec.options);
			const shown = differenceText(fromSI(Math.abs(r), displayUnit(spec.category, prefs)));
			return signedText(unit ? `${shown} ${unit}` : shown, r);
		},
		tolerance: (tol) => `±${formatValue(tol, spec.category, prefs, 4)}`,
		unit: f.unit(spec.category, spec.options)
	};
}

const PUMP_STATUS_WORDS: Readonly<Record<string, string>> = {
	running: 'running',
	off: 'off',
	no_flow: 'no flow'
};

/** One state in words, for a state change ("running", "at maximum speed", "closed"). */
function stateWord(change: StateChange, state: string | null, project: Project): string {
	if (state === null) return 'no result';
	switch (change.aspect) {
		case 'pump_status':
			return PUMP_STATUS_WORDS[state] ?? state;
		case 'pump_control':
			return PUMP_CONTROL_STATE_LABELS[state as keyof typeof PUMP_CONTROL_STATE_LABELS] ?? state;
		case 'valve_state':
			return valveStateLabel(state as Parameters<typeof valveStateLabel>[0]).toLowerCase();
		default: {
			const text = branchPatternLabel(state, componentById(project, change.elementId));
			return text.charAt(0).toLowerCase() + text.slice(1);
		}
	}
}

/** "Transfer pump: no flow (was running)", "Transfer pump control: at maximum speed (was held)". */
export function stateChangeText(change: StateChange, context: WordsContext): string {
	const project = namesProject(context, change.elementId);
	const name = componentById(project, change.elementId)?.name ?? change.elementId;
	const aspect =
		change.aspect === 'pump_control'
			? ' control'
			: change.aspect === 'branch_pattern'
				? ' pattern'
				: '';
	return `${name}${aspect}: ${stateWord(change, change.after, project)} (was ${stateWord(change, change.before, project)})`;
}

