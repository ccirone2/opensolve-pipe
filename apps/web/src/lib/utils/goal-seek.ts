/** The results reached (§6.9): Result, Reached, Target, Off by, Tolerance, Met. */
export function goalSeekGoalsTable(
	response: GoalSeekResponse,
	context: WordsContext,
	request: GoalSeekRequest
): Table {
	const views = runViews(context, request);
	const columns = [
		{ key: 'reached', label: 'Reached', numeric: true },
		{ key: 'target', label: 'Target', numeric: true },
		{ key: 'offBy', label: 'Off by', numeric: true },
		{ key: 'tolerance', label: 'Tolerance', numeric: true },
		{ key: 'met', label: 'Met' }
	];
	const rows: Row[] = response.result.goals.map((g) => {
		const view = views.goals[g.index] as GoalView;
		const goal = request.goals[g.index] as Goal;
		return {
			key: String(g.index),
			element: {
				kind: goalGroup(goal.quantity) === 'connection' ? 'connection' : 'component',
				id: goal.elementId
			},
			name: view.label,
			detail: '',
			cells: {
				reached: g.value === null ? '—' : view.value(g.value),
				target: view.target(goal.target),
				offBy: g.residual === null ? '—' : view.offBy(g.residual),
				tolerance: `${view.tolerance(g.tolerance)} (${g.toleranceSource === 'user' ? 'entered' : 'default'})`,
				met: g.met ? 'Yes' : g.value === null ? `No: ${g.message}` : 'No'
			},
			flags: []
		};
	});
	return { columns, rows };
}

/**
 * The trial solves (§6.9): Why, each variable and goal in display units, Result and States; the
 * reported trial marked. Trials are numbered from 1 (evaluation 0 is trial 1).
 */
export function goalSeekTrialTable(
	response: GoalSeekResponse,
	context: WordsContext,
	request: GoalSeekRequest
): Table {
	const views = runViews(context, request);
	const result = response.result;
	const columns = [
		{ key: 'why', label: 'Why' },
		...views.variables.map((v, i) => ({
			key: `x${i}`,
			label: v.label,
			...(v.unit ? { unit: v.unit } : {}),
			numeric: true
		})),
		...views.goals.map((g, j) => ({
			key: `g${j}`,
			label: g.label,
			...(g.unit ? { unit: g.unit } : {}),
			numeric: true
		})),
		{ key: 'result', label: 'Result' },
		{ key: 'states', label: 'States' }
	];
	const rows: Row[] = result.evaluations.map((e) => {
		const cells: Record<string, string> = { why: purposeText(e.purpose) };
		views.variables.forEach((v, i) => {
			const x = e.variableValues[i];
			cells[`x${i}`] =
				x === undefined
					? '—'
					: formatValue(x, v.spec.category, context.prefs, 6, { ...v.spec.options, unit: false });
		});
		views.goals.forEach((g, j) => {
			const value = e.goalValues[j];
			cells[`g${j}`] =
				value === null || value === undefined
					? `— (${e.outcome === 'usable' ? 'no value' : outcomeLabel(e)})`
					: g.value(value);
		});
		cells.result = outcomeLabel(e);
		cells.states = e.stateChanges.map((c) => stateChangeText(c, context)).join('; ');
		return {
			key: String(e.index),
			element: { kind: 'component', id: '' },
			name: `Trial ${e.index + 1}${e.index === result.reportedEvaluation ? ' (reported)' : ''}`,
			detail: '',
			cells,
			flags: []
		};
	});
	return { columns, rows };
}

export interface ReportContext extends WordsContext {
	projectName: string;
	/** "base case" or "scenario Winter (S2)". */
	caseText: string;
	/** When the request was sent (ms since the epoch); written in local time. */
	startedAt: number;
	/**
	 * The local time's offset from UTC in minutes (−Date.getTimezoneOffset()), so the run time is
	 * written from it by arithmetic (the export's snapshot, export.md §2.9); without it, the
	 * machine's time zone.
	 */
	utcOffsetMinutes?: number;
	stale: boolean;
	/** The physically invalid flags at the values found, in words (ws.flagText). */
	invalidFlags: readonly string[];
	/** The solved state at the values found converged. */
	converged: boolean;
}

function localDateTime(ms: number, utcOffsetMinutes?: number): string {
	const pad = (n: number) => String(n).padStart(2, '0');
	if (utcOffsetMinutes !== undefined) {
		const d = new Date(ms + utcOffsetMinutes * 60_000);
		return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())} ${pad(d.getUTCHours())}:${pad(d.getUTCMinutes())}`;
	}
	const d = new Date(ms);
	return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}`;
}

export function localDate(ms: number): string {
	return localDateTime(ms).slice(0, 10);
}

/** "converged, no physically invalid results", or the flags at the values found. */
export function atValuesText(converged: boolean, invalidFlags: readonly string[]): string {
	if (!converged) return 'did not converge';
	if (!invalidFlags.length) return 'converged, no physically invalid results';
	const n = invalidFlags.length;
	return `${n} physically invalid result${n === 1 ? '' : 's'}: ${invalidFlags.join(' ')}`;
}

/**
 * The text Copy report copies (§6.9): the case, the run, the outcome, each value found (with its
 * exact SI value and bounds), each result reached, the notes, the flags at the values found, the
 * method (the API's Goal seek section with references) and the trial solves, tab-separated so they
 * paste into a spreadsheet.
 */
export function goalSeekReport(
	response: GoalSeekResponse,
	request: GoalSeekRequest,
	context: ReportContext
): string {
	const result = response.result;
	const views = runViews(context, request);
	const banner = outcomeText(response, context, request);
	const lines: string[] = [
		`Goal seek: ${context.projectName}`,
		`Case: ${context.caseText}`,
		`Run: ${localDateTime(context.startedAt, context.utcOffsetMinutes)}; ${result.evaluations.length} trial solves in ${seconds(response.computeTime)} s; calculation method ${result.methodVersion}`
	];
	if (context.stale) lines.push('Out of date: the project changed after this goal seek.');
	lines.push(`Outcome: ${banner.title.toLowerCase()}. ${result.message}`, '', 'Inputs changed');
	for (const v of result.variables) {
		const view = views.variables[v.index] as VariableView;
		const variable = request.variables[v.index] as GoalVariable;
		const found =
			v.value === null ? 'no value' : `${view.text(v.value)} (stored ${String(v.value)})`;
		const bound = v.atBound ? `, at the ${v.atBound} bound` : '';
		lines.push(
			`  ${view.label}: ${found}${bound}, was ${caseValueText(context, v)}; bounds ${view.text(variable.lower)} to ${view.text(variable.upper)}`
		);
	}
	lines.push('Results reached');
	for (const g of result.goals) {
		const view = views.goals[g.index] as GoalView;
		const goal = request.goals[g.index] as Goal;
		const reached = g.value === null ? `no value (${g.message})` : view.value(g.value);
		const off = g.residual === null ? '' : `; off by ${view.offBy(g.residual)}`;
		lines.push(
			`  ${view.label}: ${reached}; target ${view.target(goal.target)}${off}; tolerance ${view.tolerance(g.tolerance)} (${g.toleranceSource === 'user' ? 'entered' : 'default'}); ${g.met ? 'met' : 'not met'}`
		);
	}
	if (result.notes.length) {
		lines.push('Notes');
		for (const note of result.notes) lines.push(`  ${noteText(note, response, context, request)}`);
	}
	lines.push(
		'At the values found',
		`  ${response.solvedState ? atValuesText(context.converged, context.invalidFlags) : 'no usable trial solve'}`
	);
	lines.push('Method', `  ${result.methods.title}`);
	for (const item of result.methods.items) lines.push(`  - ${item}`);
	if (result.methods.references.length) {
		lines.push('  References');
		for (const reference of result.methods.references) lines.push(`  - ${reference}`);
	}
	const table = goalSeekTrialTable(response, context, request);
	const heading = (c: { label: string; unit?: string }) =>
		c.unit ? `${c.label} (${c.unit})` : c.label;
	lines.push('Trial solves', `  ${['Trial', ...table.columns.map(heading)].join('\t')}`);
	for (const row of table.rows) {
		lines.push(
			`  ${[row.name, ...table.columns.map((c) => String(row.cells[c.key] ?? ''))].join('\t')}`
		);
	}
	return lines.join('\n');
}

