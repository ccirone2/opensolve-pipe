/** A variable the picker offers (the value it varies, before bounds are chosen). */
export interface VariableChoice {
	value: string;
	group: VariableGroup;
	label: string;
	target: ChangeTarget;
	field: string;
	coefficient?: Coefficient;
}

function variableGroup(component: Component, field: string): VariableGroup {
	switch (component.type) {
		case 'pump':
			return 'pump';
		case 'valve':
			return field === 'resistance' ? 'resistance' : 'controlValve';
		case 'reservoir':
			return 'reservoir';
		case 'reference_node':
			return 'referenceNode';
		case 'equipment':
			return 'equipment';
		case 'orifice':
			return 'orifice';
		default:
			return 'assignedFlow';
	}
}

/** The picker's order of a component's values (§6.5's table); a field not listed comes last. */
const FIELD_ORDER = [
	'speed',
	'control.setpoint',
	'setpoint',
	'resistance',
	'liquidLevel',
	'surfacePressure',
	'pressure',
	'flow',
	'rating.pressureLoss',
	'rating.flow',
	'rating.density',
	'rating.value',
	'boreDiameter',
	'dischargeCoefficient'
];

function fieldRank(field: string): number {
	const rank = FIELD_ORDER.indexOf(field);
	return rank === -1 ? FIELD_ORDER.length : rank;
}

/** A valve's own coefficient kind, else K (a valve on its default: §6.5). */
function coefficientOf(component: Component, field: GoalVariableField): Coefficient {
	const held = component.type === 'valve' ? component.resistance?.kind : undefined;
	const kind = held && field.coefficients.includes(held) ? held : 'K';
	return kind as Coefficient;
}

/**
 * The values goal seek may vary in the case shown (§6.5), by group in the picker's order: the
 * published fields (`x-goal-variables`) the case has (a flow setpoint only with flow control, a
 * temperature only for a built-in fluid; a resistance on every valve; an equipment item's values of
 * its kind of rating: a rated point's three, or the Cv or Kv).
 */
export function variableChoices(project: Project): VariableChoice[] {
	const choices: VariableChoice[] = [];
	const add = (choice: Omit<VariableChoice, 'value' | 'label'>) => {
		const base = { ...choice, label: variableLabel(project, choice) };
		choices.push({ ...base, value: `${targetKey(choice.target)}\u0000${choice.field}` });
	};
	const byGroup = new Map<VariableGroup, Omit<VariableChoice, 'value' | 'label'>[]>();
	for (const component of project.components) {
		const fields = Object.entries(componentGoalFields(component)).sort(
			([a], [b]) => fieldRank(a) - fieldRank(b)
		);
		for (const [field, entry] of fields) {
			const target: ChangeTarget = { kind: 'component', componentId: component.id };
			if (valueOf(project, target, field) === undefined) continue;
			const group = variableGroup(component, field);
			const list = byGroup.get(group) ?? [];
			list.push({
				group,
				target,
				field,
				...(field === 'resistance' ? { coefficient: coefficientOf(component, entry) } : {})
			});
			byGroup.set(group, list);
		}
	}
	for (const group of VARIABLE_GROUPS) for (const choice of byGroup.get(group) ?? []) add(choice);
	for (const field of Object.keys(pipeGoalFields())) {
		for (const connection of project.connections) {
			connection.piping.pipes.forEach((_, pipeIndex) => {
				add({
					group: 'pipe',
					target: { kind: 'pipe', connectionId: connection.id, pipeIndex },
					field
				});
			});
		}
	}
	for (const field of Object.keys(projectGoalFields())) {
		if (valueOf(project, { kind: 'project' }, field) !== undefined) {
			add({ group: 'fluid', target: { kind: 'project' }, field });
		}
	}
	return choices;
}

/** The case's value of a variable (SI number), or null (none: a resistance on its default). */
export function variableValue(
	project: Project,
	variable: Pick<VariableDraft, 'target' | 'field' | 'coefficient'>
): number | null {
	const value = valueOf(project, variable.target, variable.field);
	if (typeof value === 'number') return value;
	if (variable.field === 'resistance' && value && typeof value === 'object') {
		const held = value as { kind?: unknown; value?: unknown };
		return held.kind === variable.coefficient && typeof held.value === 'number' ? held.value : null;
	}
	return null;
}

/**
 * A field and every whole value it is a part of (each proper prefix of its path): what a scenario
 * change that sets it may be ('fluid.temperature': it, or the whole 'fluid'; 'rating.flow': it, or
 * an equipment item's whole 'rating').
 */
export function valueAndWholes(field: string): string[] {
	const path = field.split('.');
	return path.map((_, i) => path.slice(0, path.length - i).join('.'));
}

/**
 * What "Now" needs beyond the case: the display units, the last solve's K, the last solve's
 * result of an orifice plate, the scenario shown.
 */
export interface NowContext {
	prefs: UnitPreferences;
	/** The case's last converged solve's fully open K of the valve (a resistance on its default). */
	kOpen?: number | null;
	/**
	 * The orifice plate's result in the case's last converged solve, if it is not out of date
	 * (currentOrificeResult): its C, for a C on ISO 5167-2's.
	 */
	orifice?: OrificeResult | null;
	/** The scenario shown, whose own value a variable may be ("set by Winter"). */
	scenario?: Scenario | undefined;
}

/**
 * An orifice plate's discharge coefficient at its taps in a solve (the value its
 * `dischargeCoefficient` variable varies, decision 13): the meter's C with taps, else the C that
 * sets the loss, which is the C at D and D/2 tappings that a plate without taps is defined by.
 */
export function orificeTapCoefficient(result: OrificeResult | null | undefined): number | null {
	if (!result) return null;
	return result.meterDischargeCoefficient ?? (result.taps ? null : result.dischargeCoefficient);
}

/**
 * The orifice plate's result in the case's last solve, when that solve converged and the case has
 * not changed since in a way that can change it (`stale`, the store's conservative key): what
 * goal seek's defaults and "Now" read. An out-of-date solve's D or C may belong to another pipe
 * or plate (§6 W6), so it is never read.
 */
export function currentOrificeResult(
	results: { response: SolveResponse | null; stale: boolean },
	componentId: string
): OrificeResult | null {
	const solved = results.response?.solvedState;
	if (results.stale || !solved?.converged) return null;
	return solved.orificeResults?.[componentId] ?? null;
}

/**
 * An orifice plate's D for goal seek's defaults: the inlet pipe's inner diameter as the case is
 * now (utils/orifice.ts inletBore, as the form's β line), else the current solve's (the same pipe,
 * for a library pipe before the library loads); null when neither knows it.
 */
export function orificePipeDiameter(
	inlet: InletBore,
	current: OrificeResult | null
): number | null {
	if (inlet.state === 'known') return inlet.diameter;
	return current?.pipeDiameter ?? null;
}

const CONTROL_VALVES = new Set(['prv', 'psv', 'fcv']);

/**
 * The case's value of a variable as the card's "Now" says it (§6.5): "Now 100 %", with "(set by
 * Winter)" when the scenario shown sets it and where it lies against the bounds. A resistance on
 * its default says which: Crane's K at the connected diameter (from the last solve) for an
 * isolation or check valve, ideal for a control valve; one of another kind than the variable's,
 * that the search starts at the middle of the bounds.
 */
export function nowText(project: Project, variable: VariableDraft, context: NowContext): string {
	const component = componentOf(project, variable.target);
	const held = valueOf(project, variable.target, variable.field);
	const value = variableValue(project, variable);
	let text: string;
	let start = '';
	if (variable.field === 'dischargeCoefficient' && value === null) {
		// No entered C: ISO 5167-2's, the default (decision 21's start rule, as a resistance's).
		// The C at the plate's taps, or at D and D/2 tappings for a plate without taps (decision 13).
		const c = orificeTapCoefficient(context.orifice);
		const where = context.orifice?.taps ? "the plate's taps" : 'D and D/2 tappings';
		text =
			c !== null
				? `ISO 5167-2's discharge coefficient, the default (${formatValue(c, 'dimensionless', context.prefs, 4)} at ${where} in the last solve)`
				: "ISO 5167-2's discharge coefficient, the default";
		start = '; the search starts at the middle of the bounds';
	} else if (variable.field === 'resistance' && value === null) {
		if (held && typeof held === 'object') {
			const other = held as { kind?: string; value?: number };
			text = `${other.kind} ${formatValue(other.value ?? null, 'dimensionless', context.prefs, 6)}`;
			start = `; the search starts at the middle of the bounds (it varies ${variable.coefficient ?? 'K'})`;
		} else if (component?.type === 'valve' && CONTROL_VALVES.has(component.valveType)) {
			text = 'ideal (K = 0, no loss when fully open)';
			start = '; the search starts at the middle of the bounds';
		} else {
			const k = context.kOpen;
			text =
				typeof k === 'number' && k > 0
					? `default (Crane K ${formatValue(k, 'dimensionless', context.prefs, 4)} at the connected diameter)`
					: 'default (Crane K at the connected diameter; solve to see it)';
			start = '; the search starts at the middle of the bounds';
		}
	} else {
		text =
			value === null ? '—' : variableText(value, variableSpec(project, variable), context.prefs);
	}
	const fields = valueAndWholes(variable.field);
	const own = context.scenario
		? fields.some((f) => findChange(context.scenario, variable.target, f))
		: false;
	const by = own && context.scenario ? ` (set by ${context.scenario.name})` : '';
	const outside =
		value !== null && (value < variable.lower || value > variable.upper)
			? ', outside the bounds: the search starts at the nearer bound'
			: '';
	return `Now ${text}${by}${outside}${start}`;
}

/** The defaults of a variable in words, while both bounds equal them: "Defaults: 20 % to 100 %." */
export function defaultsText(
	project: Project,
	variable: VariableDraft,
	prefs: UnitPreferences
): string {
	const { lower, upper, defaults } = variable;
	if (lower !== defaults.lower || upper !== defaults.upper) return '';
	const spec = variableSpec(project, variable);
	return `Defaults: ${variableText(lower, spec, prefs)} to ${variableText(upper, spec, prefs)}.`;
}

/**
 * "Last solve: 18.99 L/s." from the case's latest converged response (out of date said so), "Last
 * solve: no value." when it has none; '' without a converged response (§6.4).
 */
export function lastSolveText(
	goal: GoalRef,
	response: SolveResponse | null,
	stale: boolean,
	prefs: UnitPreferences,
	read?: { structure: Project; sent: Project | null }
): string {
	if (!response || !(response.success && response.solvedState.converged)) return '';
	const solved = response.solvedState;
	// A connection's value is read on it as it is now (Compare's reading): the goal names its ends now.
	const found = read
		? compareValue(goalRow(goal), { solved, converged: true, sent: read.sent }, read.structure)
		: { value: goalValue(solved, goal) };
	const value = typeof found.value === 'number' ? found.value : null;
	const spec = goalSpec(goal.quantity);
	const shown =
		found.note === ENDS_NOTE
			? 'none, its ends changed since'
			: found.note === PIPES_NOTE
				? 'none, its pipes changed since'
				: value === null
					? 'no value'
					: new Formatter(prefs).value(value, spec.category, spec.options);
	const state = [stale && 'out of date', found.note === REVERSED_NOTE && 'reversed since'].filter(
		Boolean
	);
	return `Last solve${state.length ? ` (${state.join(', ')})` : ''}: ${shown}.`;
}

/** The bounds of a variable's number: its field's (schema, a valve type's), ordered with others. */
export function fieldBounds(
	project: Project,
	variable: Pick<VariableDraft, 'target' | 'field'>
): Bounds {
	const entry = variableField(project, variable.target, variable.field);
	if (!entry) return {};
	const component = componentOf(project, variable.target);
	const own =
		variable.field === 'setpoint' && component?.type === 'valve'
			? setpointBounds(component.valveType)
			: schemaBounds(entry.schema, entry.path[entry.path.length - 1] ?? variable.field);
	return component ? intersectBounds(own, orderedBounds(component, variable.field)) : own;
}

/** The variable schema's ordered pairs (`x-ordered-fields`: lower below upper). */
function boundPairs(variable: Pick<VariableDraft, 'target'>) {
	const name = goalVariableSchemaName(variable.target.kind);
	return name ? schemaOrderedFields(name) : [];
}

/**
 * The bounds of a variable's From and To fields (§6.5): the field's own bounds, each other's by
 * the variable schema's `x-ordered-fields` (lower below upper, strict).
 */
export function variableBounds(
	project: Project,
	variable: VariableDraft
): { lower: Bounds; upper: Bounds } {
	const field = fieldBounds(project, variable);
	const pairs = boundPairs(variable);
	const values = { lower: variable.lower, upper: variable.upper };
	return {
		lower: intersectBounds(field, pairBounds(pairs, values, 'lower')),
		upper: intersectBounds(field, pairBounds(pairs, values, 'upper'))
	};
}

/** Whether a variable's bounds are in order (`x-ordered-fields` of its schema). */
export function boundsInOrder(
	variable: Pick<VariableDraft, 'target' | 'lower' | 'upper'>
): boolean {
	return boundPairs(variable).every((pair) => {
		const values = variable as unknown as Record<string, number>;
		const lower = values[pair.lower];
		const upper = values[pair.upper];
		if (typeof lower !== 'number' || typeof upper !== 'number') return true;
		return pair.strict ? lower < upper : lower <= upper;
	});
}

function clip(value: number, bounds: Bounds): number {
	let x = value;
	if (bounds.minimum !== undefined) x = Math.max(x, bounds.minimum);
	if (bounds.maximum !== undefined) x = Math.min(x, bounds.maximum);
	return x;
}

/**
 * What the default bounds need beyond the case: the last solve's K, an orifice plate's pipe bore
 * and last result, and the fluid's ranges.
 */
export interface DefaultBoundsContext {
	/** The case's last converged solve's fully open K of the valve (a resistance on its default). */
	kOpen?: number | null;
	/**
	 * An orifice plate's D, its inlet pipe's inner diameter (orificePipeDiameter: as the case is
	 * now, else the current solve's); absent or null: unknown.
	 */
	pipeDiameter?: number | null;
	/**
	 * The orifice plate's result in the case's last converged solve, if it is not out of date
	 * (currentOrificeResult; absent: none).
	 */
	orifice?: OrificeResult | null;
	/** The API's information on the case's built-in fluid (absent: not loaded). */
	fluid?: FluidInfo;
}

const BAR = 1e5;

/**
 * The most an entered C at corner or flange taps may reach in a default box once moved to D and
 * D/2 tappings, C · r_max (decision 17 (c) refuses above 1): 0.99, the designers' margin (§6 W6),
 * or the case's own where that is more. The case's own value is always in the box (the case
 * builds, or its own topology issue comes first).
 */
const MOVED_LIMIT = 0.99;

/**
 * The most C · r_max may reach at a bound other than the case's own: 1 − 10⁻⁹, room for the
 * difference between the web's r_max and the API's (below 10⁻¹² relative, orifice-bound.test.ts),
 * which decides at exactly 1.
 */
const ROUND_OFF_LIMIT = 1 - 1e-9;

/** An orifice plate with corner or flange taps, whose entered C is moved (decision 13); else null. */
function movedTaps(component: Component | undefined): 'corner' | 'flange' | null {
	if (component?.type !== 'orifice') return null;
	return component.taps === 'corner' || component.taps === 'flange' ? component.taps : null;
}

/**
 * The largest C a default box may hold for an orifice plate with corner or flange taps: C · r_max
 * at most 0.99 at its D, d and taps, or the case's entered C where that is more; without D, the
 * case's entered C (the case builds, or its own topology issue comes first), or on ISO 5167-2's C
 * 0.99 ÷ RATIO_BOUND_ANY, the bound for any plate the API builds. Null for other plates (no move:
 * C ≤ 1 is the field's own bound).
 */
function movedCoefficientCap(
	component: Component | undefined,
	pipe: number | null | undefined,
	entered: number | null
): number | null {
	const taps = movedTaps(component);
	if (!taps || component?.type !== 'orifice') return null;
	const own = entered !== null && entered > 0 ? entered : null;
	const ratio =
		typeof pipe === 'number' ? movedRatioBound(pipe, component.boreDiameter, taps) : null;
	if (ratio !== null) return Math.max(MOVED_LIMIT / ratio, own ?? 0);
	return own ?? MOVED_LIMIT / RATIO_BOUND_ANY;
}

/**
 * `bound` if `ok` holds there, else the bound nearest it, between it and `start` (the case's own
 * value, which builds), where `ok` holds, by bisection (60 halvings); `start` when none does.
 * The API checks a box at its bounds only (decision 21), so a bound where `ok` holds suffices.
 */
function towardStart(ok: (value: number) => boolean, start: number, bound: number): number {
	if (bound === start || ok(bound)) return bound;
	let good = start;
	let bad = bound;
	for (let i = 0; i < 60; i++) {
		const mid = (good + bad) / 2;
		if (ok(mid)) good = mid;
		else bad = mid;
	}
	return good;
}

/**
 * The fluid's temperature range for a glycol at its concentration: the freezing point there (the
 * higher of the two tabulated freezing points around it, so the bound is inside the range).
 */
function temperatureRange(project: Project, info: FluidInfo): { min: number; max: number } {
	const { min, max } = info.temperatureRange;
	const fluid = project.fluid;
	const points = info.freezingPoints ?? [];
	if (fluid.kind !== 'builtin' || typeof fluid.concentration !== 'number' || !points.length) {
		return { min, max };
	}
	const c = fluid.concentration;
	const below = points.filter((p) => p.concentration <= c).at(-1);
	const above = points.find((p) => p.concentration >= c);
	const freezing = Math.max(below?.temperature ?? min, above?.temperature ?? min);
	return { min: Math.max(min, freezing), max };
}

/**
 * Default bounds of a variable (§6.6): pre-fill values only, clipped to the field's bounds. "Now"
 * is the case's value; for a resistance on its default it is the last converged solve's K (so the
 * API's middle start, the geometric mean, is the case's own K), else 1.
 */
export function defaultBounds(
	project: Project,
	variable: Pick<VariableDraft, 'target' | 'field' | 'coefficient'>,
	context: DefaultBoundsContext = {}
): { lower: number; upper: number } {
	const now = variableValue(project, variable);
	const component = componentOf(project, variable.target);
	let lower: number;
	let upper: number;
	switch (variable.field) {
		case 'speed': {
			const min = component?.type === 'pump' ? component.control?.minSpeed : undefined;
			if (min === undefined) {
				[lower, upper] = [0.2, 1];
				break;
			}
			// The smallest whole percent strictly above the minimum speed; halfway to 100 % when
			// that would be 100 % (a controlled pump's maximum speed stays above its minimum).
			let percent = Math.floor(min * 100) + 1;
			while (percent / 100 <= min) percent++;
			[lower, upper] = [percent < 100 ? percent / 100 : (min + 1) / 2, 1];
			break;
		}
		case 'control.setpoint':
			[lower, upper] = [0.1 * (now ?? 0), 3 * (now ?? 0)];
			break;
		case 'setpoint':
			if (component?.type === 'valve' && component.valveType === 'fcv') {
				[lower, upper] = [0, now ? 3 * now : 0.01];
				break;
			}
		// falls through: a PRV's or PSV's setpoint is a pressure
		case 'surfacePressure':
		case 'pressure': {
			const v = now ?? 0;
			[lower, upper] = [v >= 0 ? Math.max(0, v - 5 * BAR) : v - 5 * BAR, v + 5 * BAR];
			break;
		}
		case 'liquidLevel': {
			const v = now ?? 0;
			[lower, upper] = [0, v + Math.max(20, 2 * v)];
			break;
		}
		case 'flow': {
			const q = now ?? 0;
			[lower, upper] = q > 0 ? [0, 3 * q] : q < 0 ? [3 * q, 0] : [0, 0.01];
			break;
		}
		case 'length': {
			const v = now ?? 1;
			[lower, upper] = [v / 10, 10 * v];
			break;
		}
		case 'fluid.temperature': {
			const v = now ?? 293.15;
			if (context.fluid) {
				const range = temperatureRange(project, context.fluid);
				[lower, upper] = [range.min + 1, range.max - 1];
			} else [lower, upper] = [v - 20, v + 20];
			break;
		}
		case 'resistance': {
			const kOpen = context.kOpen;
			const v = now ?? (kOpen && kOpen > 0 ? kOpen : 1);
			[lower, upper] = [v / 100, 100 * v];
			break;
		}
		case 'rating.pressureLoss':
		case 'rating.flow':
		case 'rating.value': {
			// Designers' default (equipment-pressure-drop.md §6.4): a factor of 10 either way. A Cv or
			// Kv is a rated flow at a stated drop (c ∝ 1/Cv², as c ∝ 1/Q_r²): the rated flow's range,
			// narrower than a valve resistance's on purpose (always shown and editable, D16).
			const v = now ?? 1;
			[lower, upper] = [v / 10, 10 * v];
			break;
		}
		case 'rating.density': {
			const v = now ?? 1;
			[lower, upper] = [v / 2, 2 * v];
			break;
		}
		case 'boreDiameter': {
			// Designers' default (orifice-plate.md §6 W6): ISO 5167-2's β range, 0.1 D to 0.75 D,
			// widened to hold the case's bore. Without D, half the bore to the bore: a valid plate's
			// bore is below D, so the default never reaches it (the user can raise it).
			const d = now ?? 0;
			const D = context.pipeDiameter;
			const known = typeof D === 'number' && D > 0;
			[lower, upper] = known ? [Math.min(0.1 * D, d), Math.max(0.75 * D, d)] : [d / 2, d];
			// An entered C at corner or flange taps is moved to D and D/2 tappings by r, whose bound
			// r_max depends on the bore: each bound keeps C · r_max at most 0.99, or at most the
			// case's own where that is more (decision 17 (c)), moved toward the case's bore where it
			// would not, or to the case's bore itself (which builds).
			const taps = movedTaps(component);
			const c = component?.type === 'orifice' ? component.dischargeCoefficient : null;
			if (known && taps && typeof c === 'number' && c > 0) {
				const moved = (bore: number) => {
					const ratio = movedRatioBound(D, bore, taps);
					return ratio === null ? Infinity : c * ratio;
				};
				const own = moved(d);
				const limit = Math.max(MOVED_LIMIT, Math.min(own, ROUND_OFF_LIMIT));
				const ok = (bore: number) => moved(bore) <= limit;
				[lower, upper] = [towardStart(ok, d, lower), towardStart(ok, d, upper)];
			}
			break;
		}
		case 'dischargeCoefficient': {
			// Half to twice the case's entered C, or the current solve's C at the plate's taps, at
			// most 1; with neither value, 0.5 to 1. At corner or flange taps every C of the box,
			// moved to D and D/2 tappings, stays at most 0.99 (decision 17 (c), movedCoefficientCap),
			// before any solve and whatever state the last one held its C in.
			const v = now ?? orificeTapCoefficient(context.orifice);
			[lower, upper] = v !== null && v > 0 ? [v / 2, Math.min(2 * v, 1)] : [0.5, 1];
			const cap = movedCoefficientCap(component, context.pipeDiameter, now);
			if (cap !== null) {
				upper = Math.min(upper, cap);
				// Half the cap when it falls to the lower bound (0.5, without a C): From below To.
				if (lower >= upper) lower = upper / 2;
			}
			break;
		}
		default:
			[lower, upper] = [now ?? 0, now ?? 1];
	}
	const bounds = fieldBounds(project, variable);
	return { lower: clip(lower, bounds), upper: clip(upper, bounds) };
}

/** The record a pipe variable keeps of its connection: pipe count and ends (§6.5). */
function pipesRecord(
	project: Project,
	connectionId: string
): { count: number; ends: string } | undefined {
	const c = connectionById(project, connectionId);
	if (!c) return undefined;
	return {
		count: c.piping.pipes.length,
		ends: `${c.fromComponentId}:${c.fromPortId}\u0000${c.toComponentId}:${c.toPortId}`
	};
}

/** A new variable for a choice, with its default bounds and the records its lapses need. */
export function newVariable(
	project: Project,
	choice: Pick<VariableChoice, 'target' | 'field' | 'coefficient'>,
	context: DefaultBoundsContext = {}
): VariableDraft {
	const defaults = defaultBounds(project, choice, context);
	const component = componentOf(project, choice.target);
	const pipes =
		choice.target.kind === 'pipe' ? pipesRecord(project, choice.target.connectionId) : undefined;
	return {
		target: choice.target,
		field: choice.field,
		...(choice.coefficient ? { coefficient: choice.coefficient } : {}),
		...defaults,
		defaults,
		...(pipes ? { pipes } : {}),
		...(choice.field === 'setpoint' && component?.type === 'valve'
			? { valveType: component.valveType }
			: {})
	};
}

