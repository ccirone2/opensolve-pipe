/** An element the goal picker offers: a port, a connection or a component, in its group. */
export interface GoalElement {
	/** Unique among the options: the group and the ids. */
	value: string;
	group: GoalGroup;
	label: string;
	elementId: string;
	portId?: string;
}

/** The schemas the quantities of a group may name (`x-goal-quantities` targets). */
function groupTargets(group: GoalGroup): Set<string> {
	return new Set(
		GOAL_QUANTITY_ORDER.filter((q) => goalGroup(q) === group).flatMap((q) => rule(q).targets)
	);
}

/** The schema name a goal quantity's targets use for an element ('PipeConnection' for one). */
function elementSchema(project: Project, elementId: string, group: GoalGroup): string | null {
	if (group === 'connection') return connectionById(project, elementId) ? 'PipeConnection' : null;
	const component = componentById(project, elementId);
	return component ? componentSchemaName(component) : null;
}

/**
 * The elements a goal may be on, by group in the picker's order (§6.4): every port, every pipe
 * connection, then the components the quantities of each group may name (`x-goal-quantities`).
 */
export function goalElements(project: Project): GoalElement[] {
	const options: GoalElement[] = [];
	const ports = groupTargets('port');
	for (const c of project.components) {
		if (!ports.has(componentSchemaName(c) ?? '')) continue;
		for (const p of c.ports) {
			options.push({
				value: `port\u0000${c.id}\u0000${p.id}`,
				group: 'port',
				label: `${portLabel(p.id)} of ${c.name}`,
				elementId: c.id,
				portId: p.id
			});
		}
	}
	if (groupTargets('connection').has('PipeConnection')) {
		for (const c of project.connections) {
			options.push({
				value: `connection\u0000${c.id}`,
				group: 'connection',
				label: connectionName(project, c.id),
				elementId: c.id
			});
		}
	}
	for (const group of ['pump', 'valve', 'equipment', 'orifice', 'boundary'] as const) {
		const targets = groupTargets(group);
		for (const c of project.components) {
			if (!targets.has(componentSchemaName(c) ?? '')) continue;
			options.push({ value: `${group}\u0000${c.id}`, group, label: c.name, elementId: c.id });
		}
	}
	return options;
}

/** The quantities a goal on `element` may read, in the picker's order. */
export function goalChoices(project: Project, element: GoalElement): GoalQuantity[] {
	const schema = elementSchema(project, element.elementId, element.group);
	return GOAL_QUANTITY_ORDER.filter(
		(q) => goalGroup(q) === element.group && !!schema && rule(q).targets.includes(schema)
	);
}

/** What the case must have for a quantity's `needs` (`x-goal-quantities`), by need. */
const NEED_CHECKS: Readonly<
	Record<string, (project: Project, elementId: string, fluid?: FluidInfo) => string | null>
> = {
	vaporPressure: (project, _id, info) => {
		const fluid = project.fluid;
		const has =
			fluid.kind === 'custom'
				? fluid.vaporPressure != null
				: fluid.overrides?.vaporPressure != null || info?.vaporPressureAvailable !== false;
		return has ? null : 'the fluid has no vapor pressure';
	},
	npshrCurve: (project, id) => {
		const pump = componentById(project, id);
		if (pump?.type !== 'pump') return null;
		const curve = project.pumpLibrary.find((c) => c.id === pump.curveId);
		return curve && !curve.npshrCurve ? "the pump's curve has no NPSHr" : null;
	},
	// A meter's reading is at its taps: a plate without taps (a restriction orifice) has none.
	taps: (project, id) => {
		const plate = componentById(project, id);
		if (plate?.type !== 'orifice') return null;
		return plate.taps ? null : 'the orifice plate has no pressure taps, so it has no reading';
	}
};

/**
 * Why the case cannot give `quantity` on `elementId` (a published need it lacks: "the fluid has no
 * vapor pressure"), or null. `fluid`: the API's information on the case's built-in fluid (absent:
 * not loaded, so a vapor pressure is not ruled out; the API checks it either way).
 */
export function goalNeedProblem(
	project: Project,
	quantity: GoalQuantity,
	elementId: string,
	fluid?: FluidInfo
): string | null {
	for (const need of rule(quantity).needs) {
		const problem = NEED_CHECKS[need]?.(project, elementId, fluid) ?? null;
		if (problem) return problem;
	}
	return null;
}

