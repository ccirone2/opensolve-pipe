/**
 * Scenarios (PRD §3.8, SDD §4.12, docs/proposals/scenario-manager.md §6): named sets of changes
 * ("overrides" in the API) of base-project values. A scenario changes values only, never
 * components, connections, ports or pipe counts. Which values it may change is the API's
 * allow-list, published as `x-override-fields` (model-rules.ts), never copied here.
 *
 * This is the client mirror of the API's services/scenarios.py, for display and editing only:
 * - applyScenario / caseProject: the project a case is (the base with a scenario's changes), so
 *   forms show and edit a scenario's values. Results always come from, and show, the server's
 *   own record of what it applied (SolveResponse.scenario).
 * - scenarioEdit: an edit made while a scenario is shown, sorted into the scenario's changes
 *   (allow-list values), shared edits (names, project name and description, display units:
 *   the same in every case) and refused edits (anything else).
 * - carryChanges: a base edit that moves pipes (a join, a reversal, an insertion that turns a
 *   connection) or removes one carries the scenarios' pipe changes with their pipes (identity.ts).
 *
 * A change whose target is gone (a deleted component, connection or pipe) is kept and is
 * "orphaned"; one whose target has no such value (a flow setpoint on a pump without flow
 * control) is "not applicable". Both are ignored when solving, and the UI says they no longer
 * apply. The shared fixture __fixtures__/scenario-cases.json, generated by the API with the real
 * apply_scenario, checks this mirror (scenarios.test.ts).
 */
