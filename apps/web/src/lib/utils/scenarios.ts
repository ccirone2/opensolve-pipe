/** A component field as the panel names it ('liquidLevel' → 'Liquid level'). */
export function fieldLabelFor(component: Component | undefined, field: string): string {
	switch (field) {
		case 'status':
			return 'Status';
		case 'speed':
			return component?.type === 'pump' && component.control ? 'Maximum speed' : 'Speed';
		case 'control.setpoint':
			return 'Flow setpoint';
		case 'setpoint':
			if (component?.type === 'valve' && component.valveType === 'prv')
				return 'Outlet pressure setpoint';
			if (component?.type === 'valve' && component.valveType === 'psv')
				return 'Inlet pressure setpoint';
			return component?.type === 'valve' && component.valveType === 'fcv'
				? 'Flow setpoint'
				: 'Setpoint';
		case 'resistance':
			return 'Resistance';
		case 'liquidLevel':
			return 'Liquid level';
		case 'surfacePressure':
			return 'Surface pressure';
		case 'pressure':
			return 'Pressure';
		case 'flow':
			return 'Assigned flow';
		default:
			return humanize(field.replace(/\./g, ' '));
	}
}

/** The field a change sets, as the panel names it: 'Liquid level', 'Pipe size and material', ... */
export function changeFieldLabel(project: Project, override: Override): string {
	if (override.kind === 'component') {
		return fieldLabelFor(componentById(project, override.componentId), override.field);
	}
	if (override.kind === 'pipe') return humanize(PIPE_FIELD_NAMES[override.field] ?? override.field);
	return override.field === 'fluid' ? 'Fluid' : 'Fluid temperature';
}

/** What a change is of: the component's name, "Pipe 2 of Supply → Pump A", or "Project fluid". */
export function changeTargetLabel(project: Project, override: Override): string {
	if (override.kind === 'component') {
		const component = componentById(project, override.componentId);
		return component ? component.name : `${override.componentId} (deleted)`;
	}
	if (override.kind === 'pipe') {
		const connection = connectionById(project, override.connectionId);
		if (!connection) return `Pipe ${override.pipeIndex + 1} of ${override.connectionId} (deleted)`;
		const from =
			componentById(project, connection.fromComponentId)?.name ?? connection.fromComponentId;
		const to = componentById(project, connection.toComponentId)?.name ?? connection.toComponentId;
		return `Pipe ${override.pipeIndex + 1} of ${from} → ${to}`;
	}
	return 'Project';
}

export interface ValueTextOptions {
	/** The material's name from the pipe library ('Carbon steel'); default: the id, humanized. */
	materialName?: (id: string) => string | undefined;
	/** Nominal sizes with their NPS designation, for "NPS 2-1/2". */
	nominalSizes?: readonly { nominalSize: number; nps: string }[];
}

function statusText(component: Component | undefined, value: unknown): string {
	const key = String(value);
	const labels: Readonly<Record<string, string>> =
		component?.type === 'pump'
			? PUMP_STATUS_LABELS
			: component?.type === 'valve' && ['check', 'stop_check'].includes(component.valveType)
				? CHECK_STATUS_LABELS
				: component?.type === 'valve' && ['prv', 'psv', 'fcv'].includes(component.valveType)
					? CONTROL_STATUS_LABELS
					: ISOLATION_STATUS_LABELS;
	return labels[key] ?? humanize(key);
}

function specText(value: unknown, units: UnitPreferences, options: ValueTextOptions): string {
	if (!isRecord(value)) return 'not a pipe specification';
	const id = String(value.materialId ?? '');
	if (id === 'custom') {
		const parts = ['Custom pipe'];
		if (typeof value.innerDiameter === 'number')
			parts.push(`inner diameter ${formatValue(value.innerDiameter, 'diameter', units)}`);
		if (typeof value.roughness === 'number')
			parts.push(`roughness ${formatValue(value.roughness, 'diameter', units)}`);
		return parts.join(', ');
	}
	const parts = [options.materialName?.(id) ?? humanize(id)];
	if (typeof value.schedule === 'string') parts.push(`Sch ${value.schedule}`);
	if (typeof value.nominalSize === 'number')
		parts.push(npsLabel(value.nominalSize, options.nominalSizes));
	if (typeof value.innerDiameter === 'number')
		parts.push(`inner diameter ${formatValue(value.innerDiameter, 'diameter', units)}`);
	if (typeof value.roughness === 'number')
		parts.push(`roughness ${formatValue(value.roughness, 'diameter', units)}`);
	return parts.join(', ');
}

/** A custom fluid's properties, or a built-in fluid's property overrides, with their values. */
function propertyTexts(values: JsonObject, units: UnitPreferences, suffix = ''): string[] {
	const parts: string[] = [];
	if (typeof values.density === 'number')
		parts.push(`density${suffix} ${formatValue(values.density, 'density', units)}`);
	if (typeof values.dynamicViscosity === 'number')
		parts.push(
			`dynamic viscosity${suffix} ${formatValue(values.dynamicViscosity, 'viscosity', units)}`
		);
	if (typeof values.vaporPressure === 'number')
		parts.push(
			`vapor pressure${suffix} ${formatValue(values.vaporPressure, 'pressure', units, 4, { absolute: true })}`
		);
	return parts;
}

/** A fluid with the values that define it, so a change of one property is never "X (base: X)". */
function fluidText(value: unknown, units: UnitPreferences): string {
	if (!isRecord(value)) return 'not a fluid';
	if (value.kind === 'custom') {
		let name = `${String(value.name ?? 'Custom fluid')} (custom)`;
		if (typeof value.temperature === 'number')
			name += ` at ${formatValue(value.temperature, 'temperature', units)}`;
		return [name, ...propertyTexts(value, units)].join(', ');
	}
	const id = String(value.fluidId ?? '');
	const parts = [FLUID_FALLBACK_NAMES[id] ?? humanize(id)];
	if (typeof value.temperature === 'number')
		parts.push(`at ${formatValue(value.temperature, 'temperature', units)}`);
	if (typeof value.concentration === 'number')
		parts.push(`${formatValue(value.concentration, 'fraction', units)} glycol`);
	if (isRecord(value.overrides)) parts.push(...propertyTexts(value.overrides, units, ' override'));
	return parts.join(', ');
}

/**
 * A change's value in display units: "2.50 m", "Off", "90 %", "Cv 120", "Carbon steel, Sch 40,
 * NPS 6". `project` names the target (its type decides a status's words and a setpoint's unit).
 */
export function changeValueText(
	project: Project,
	override: Override,
	value: unknown,
	units: UnitPreferences,
	options: ValueTextOptions = {}
): string {
	const number = (category: Parameters<typeof formatValue>[1], gauge = false) =>
		typeof value === 'number' ? formatValue(value, category, units, 4, { gauge }) : String(value);
	if (override.kind === 'pipe') {
		return override.field === 'spec' ? specText(value, units, options) : number('length');
	}
	if (override.kind === 'project') {
		return override.field === 'fluid' ? fluidText(value, units) : number('temperature');
	}
	const component = componentById(project, override.componentId);
	switch (override.field) {
		case 'status':
			return statusText(component, value);
		case 'speed':
			return number('fraction');
		case 'control.setpoint':
		case 'flow':
			if (override.field === 'flow' && typeof value === 'number') {
				const direction = flowDirection(value);
				const magnitude = formatValue(Math.abs(value), 'flow', units);
				return direction === 'demand'
					? `Demand ${magnitude}`
					: direction === 'supply'
						? `Supply ${magnitude}`
						: `${magnitude} (as a plug)`;
			}
			return number('flow');
		case 'setpoint':
			return component?.type === 'valve' && component.valveType === 'fcv'
				? number('flow')
				: number('pressure', true);
		case 'liquidLevel':
			return number('length');
		case 'surfacePressure':
		case 'pressure':
			return number('pressure', true);
		case 'resistance':
			if (value === null || value === undefined) return 'Default';
			if (isRecord(value))
				return `${String(value.kind)} ${formatValue(Number(value.value), 'dimensionless', units)}`;
			return String(value);
		default:
			return typeof value === 'number' ? formatValue(value, 'dimensionless', units) : String(value);
	}
}
