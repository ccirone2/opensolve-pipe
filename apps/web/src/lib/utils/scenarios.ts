/** What a change is of: a component, one pipe of a connection, or the project (the fluid). */
export type ChangeTarget =
	| { kind: 'component'; componentId: string }
	| { kind: 'pipe'; connectionId: string; pipeIndex: number }
	| { kind: 'project' };

export function changeTarget(override: Override): ChangeTarget {
	if (override.kind === 'component')
		return { kind: 'component', componentId: override.componentId };
	if (override.kind === 'pipe') {
		return { kind: 'pipe', connectionId: override.connectionId, pipeIndex: override.pipeIndex };
	}
	return { kind: 'project' };
}

/** 'component:P1', 'pipe:L1:0', 'project': equal for changes of one target. */
export function targetKey(target: ChangeTarget): string {
	if (target.kind === 'component') return `component:${target.componentId}`;
	if (target.kind === 'pipe') return `pipe:${target.connectionId}:${target.pipeIndex}`;
	return 'project';
}

/** The change of `field` on `target`, as an override with `value`. */
export function makeOverride(target: ChangeTarget, field: string, value: unknown): Override {
	if (target.kind === 'component') {
		return {
			kind: 'component',
			componentId: target.componentId,
			field: field as Extract<Override, { kind: 'component' }>['field'],
			value
		};
	}
	if (target.kind === 'pipe') {
		return {
			kind: 'pipe',
			connectionId: target.connectionId,
			pipeIndex: target.pipeIndex,
			field: field as Extract<Override, { kind: 'pipe' }>['field'],
			value
		};
	}
	return {
		kind: 'project',
		field: field as Extract<Override, { kind: 'project' }>['field'],
		value
	};
}

/** Whether `override` changes `field` of `target`. */
export function changes(override: Override, target: ChangeTarget, field: string): boolean {
	return override.field === field && targetKey(changeTarget(override)) === targetKey(target);
}

/**
 * Pairs of a scenario's changes that set one value twice, or a value and a part of it (the whole
 * fluid and its temperature): the API rejects both, so the result never depends on their order.
 */
export function overlappingChanges(
	overrides: readonly Override[]
): { first: number; second: number; part: boolean }[] {
	const found: { first: number; second: number; part: boolean }[] = [];
	overrides.forEach((later, j) => {
		const pathJ = later.field.split('.');
		for (let i = 0; i < j; i++) {
			const earlier = overrides[i] as Override;
			if (targetKey(changeTarget(earlier)) !== targetKey(changeTarget(later))) continue;
			const pathI = earlier.field.split('.');
			const prefix = (a: string[], b: string[]) =>
				a.length <= b.length && a.every((p, k) => b[k] === p);
			if (pathI.join('.') === pathJ.join('.')) found.push({ first: i, second: j, part: false });
			else if (prefix(pathI, pathJ) || prefix(pathJ, pathI)) {
				found.push({ first: i, second: j, part: true });
			}
		}
	});
	return found;
}

