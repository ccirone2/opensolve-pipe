/** The pipes scenario changes name, in a draft of the project before an edit. */
export interface PipeTracker {
	/** The pipe (a draft pipe's origin, identity.ts) → its position, 'connectionId\u0000index'. */
	positions: Map<object, string>;
}

const position = (connectionId: string, index: number) => `${connectionId}\u0000${index}`;

/** Record the draft's pipes that scenario changes name (draft: a copy of `before`). */
export function trackPipes(before: Project, draft: Project): PipeTracker {
	const named = new Set<string>();
	for (const scenario of scenariosOf(before)) {
		for (const o of overridesOf(scenario)) {
			if (o.kind === 'pipe') named.add(position(o.connectionId, o.pipeIndex));
		}
	}
	const positions = new Map<object, string>();
	if (!named.size) return { positions };
	for (const connection of draft.connections) {
		connection.piping.pipes.forEach((pipe, i) => {
			const key = position(connection.id, i);
			if (named.has(key)) positions.set(originOf(pipe), key);
		});
	}
	return { positions };
}

const PRESSURE_VALVES = new Set(['prv', 'psv']);

function namesList(names: readonly string[]): string {
	if (names.length <= 1) return names[0] ?? '';
	return `${names.slice(0, -1).join(', ')} and ${names[names.length - 1]}`;
}

/**
 * The scenarios of `next` (a base edit of `before`) with their changes carried through it:
 * - a pipe change follows its pipe (by identity, through joins, reversals and insertions); one
 *   whose pipe was removed from a connection that still exists goes with it; one whose
 *   connection is gone is kept (it no longer applies, and an undo makes it apply again);
 * - a control valve changed between a pressure valve (PRV, PSV) and a flow valve (FCV) loses its
 *   setpoint changes, whose meaning changed (the base resets its setpoint to 0 too);
 * - an equipment item whose base rating changed between a Cv and a Kv loses its coefficient
 *   changes (`rating.value`), whose meaning changed (a Cv is not a Kv; the same rule);
 * - a relief valve whose base capacity changed kind loses the changes of the old kind's values
 *   (`capacity.letter`, `capacity.area`, ...), between an effective area and a certified one its
 *   area changes too (an effective area is not an actual area; proposal pressure-relief-valve.md
 *   decision 18).
 * Notes say what happened to changes, for the user.
 */
export function carryChanges(
	before: Project,
	tracker: PipeTracker,
	next: Project
): { project: Project; notes: string[] } {
	const scenarios = scenariosOf(next);
	if (!scenarios.length || !scenariosOf(before).length) return { project: next, notes: [] };
	const notes: string[] = [];
	const moved = new Map<string, string>();
	if (tracker.positions.size) {
		for (const connection of next.connections) {
			connection.piping.pipes.forEach((pipe, i) => {
				const from = tracker.positions.get(originOf(pipe));
				if (from && !moved.has(from)) moved.set(from, position(connection.id, i));
			});
		}
	}
	const earlier = new Map(
		scenariosOf(before).map((s) => [s.id, new Set(overridesOf(s).map((o) => canonicalJson(o)))])
	);
	const removedPipes = new Map<string, Set<string>>();
	const familyChanged = new Set<string>();
	for (const component of next.components) {
		const old = componentById(before, component.id);
		if (
			old?.type === 'valve' &&
			component.type === 'valve' &&
			old.valveType !== component.valveType &&
			[old.valveType, component.valveType].some((t) => t === 'fcv') &&
			[old.valveType, component.valveType].some((t) => PRESSURE_VALVES.has(t))
		) {
			familyChanged.add(component.id);
		}
	}
	/** Equipment whose base rating changed between a Cv and a Kv, with its kind now. */
	const coefficientChanged = new Map<string, string>();
	for (const component of next.components) {
		const old = componentById(before, component.id);
		if (
			old?.type === 'equipment' &&
			component.type === 'equipment' &&
			old.rating.kind !== 'point' &&
			component.rating.kind !== 'point' &&
			old.rating.kind !== component.rating.kind
		) {
			coefficientChanged.set(component.id, component.rating.kind);
		}
	}
	/**
	 * Relief valves whose base capacity changed kind (decision 18): the scenarios' changes of the
	 * old kind's values go, since no value carries from one kind to another (an effective area is
	 * not an actual area, nor a letter's area either).
	 */
	const capacityChanged = new Map<string, { from: CapacityKind; to: CapacityKind }>();
	for (const component of next.components) {
		const old = componentById(before, component.id);
		if (
			old?.type === 'relief_valve' &&
			component.type === 'relief_valve' &&
			old.capacity.kind !== component.capacity.kind
		) {
			capacityChanged.set(component.id, { from: old.capacity.kind, to: component.capacity.kind });
		}
	}
	const valveNotes = new Map<string, Set<string>>();
	const coefficientNotes = new Map<string, Set<string>>();
	const capacityNotes = new Map<string, Set<string>>();
	let changed = false;
	const carried = scenarios.map((scenario) => {
		const known = earlier.get(scenario.id);
		if (!known) return scenario;
		const list: Override[] = [];
		const seen = new Set<string>();
		for (const o of overridesOf(scenario)) {
			let kept: Override | null = o;
			if (known.has(canonicalJson(o)) && o.kind === 'pipe') {
				const from = position(o.connectionId, o.pipeIndex);
				const to = moved.get(from);
				const oldConnection = connectionById(before, o.connectionId);
				const newConnection = connectionById(next, o.connectionId);
				if (to !== undefined) {
					const [connectionId = o.connectionId, index = '0'] = to.split('\u0000');
					kept = { ...o, connectionId, pipeIndex: Number(index) };
				} else if (
					oldConnection &&
					newConnection &&
					o.pipeIndex < oldConnection.piping.pipes.length &&
					newConnection.piping.pipes.length < oldConnection.piping.pipes.length
				) {
					kept = null; // its pipe was removed: its changes go with it
					const key = `${o.connectionId}\u0000${o.pipeIndex}`;
					if (!removedPipes.has(key)) removedPipes.set(key, new Set());
					removedPipes.get(key)!.add(scenario.name);
				}
			}
			if (kept && known.has(canonicalJson(o)) && kept.kind === 'component') {
				if (kept.field === 'setpoint' && familyChanged.has(kept.componentId)) {
					if (!valveNotes.has(kept.componentId)) valveNotes.set(kept.componentId, new Set());
					valveNotes.get(kept.componentId)!.add(scenario.name);
					kept = null;
				} else if (kept.field === 'rating.value' && coefficientChanged.has(kept.componentId)) {
					if (!coefficientNotes.has(kept.componentId)) {
						coefficientNotes.set(kept.componentId, new Set());
					}
					coefficientNotes.get(kept.componentId)!.add(scenario.name);
					kept = null;
				} else if (
					capacityChanged.has(kept.componentId) &&
					CAPACITY_FIELDS[capacityChanged.get(kept.componentId)!.from]
						.map((field) => `capacity.${field}`)
						.includes(kept.field)
				) {
					if (!capacityNotes.has(kept.componentId)) capacityNotes.set(kept.componentId, new Set());
					capacityNotes.get(kept.componentId)!.add(scenario.name);
					kept = null;
				}
			}
			if (kept !== o) changed = true;
			if (!kept) continue;
			const key = `${targetKey(changeTarget(kept))}\u0000${kept.field}`;
			if (seen.has(key)) {
				changed = true;
				continue;
			}
			seen.add(key);
			list.push(kept);
		}
		return list.length === overridesOf(scenario).length &&
			list.every((o, i) => o === overridesOf(scenario)[i])
			? scenario
			: { ...scenario, overrides: list };
	});
	for (const [key, names] of removedPipes) {
		const [connectionId = '', index = '0'] = key.split('\u0000');
		notes.push(
			`Pipe ${Number(index) + 1} of connection ${connectionId} removed, with its changes in ${namesList([...names])}. Undo restores both.`
		);
	}
	for (const [componentId, names] of valveNotes) {
		const name = componentById(next, componentId)?.name ?? componentId;
		notes.push(
			`The setpoint changes of ${name} in ${namesList([...names])} were removed: a PRV or PSV setpoint is a pressure, an FCV's a flow.`
		);
	}
	for (const [componentId, names] of coefficientNotes) {
		const item = componentById(next, componentId);
		const was = coefficientChanged.get(componentId) === 'Cv' ? 'Kv' : 'Cv';
		notes.push(
			`The ${was} changes of ${item?.name ?? componentId} in ${namesList([...names])} were removed: it is rated by a ${coefficientChanged.get(componentId)} now, and a ${was} is not a ${coefficientChanged.get(componentId)}.`
		);
	}
	for (const [componentId, names] of capacityNotes) {
		const valve = componentById(next, componentId);
		const { from, to } = capacityChanged.get(componentId)!;
		const area =
			[from, to].includes('effective') && [from, to].includes('certified')
				? ' (an effective area is not an actual area)'
				: '';
		notes.push(
			`The capacity value changes of ${valve?.name ?? componentId} in ${namesList([...names])} were removed: its capacity is given by ${CAPACITY_KIND_WORDS[to]} now, not ${CAPACITY_KIND_WORDS[from]}, and no value carries from one kind of capacity to another${area}.`
		);
	}
	notes.push(...lapseNotes(before, next));
	notes.push(...splitNotes(before, next));
	return { project: changed ? withScenarios(next, carried) : next, notes };
}

/**
 * Notes on changes a base edit made inapplicable: flow control removed, an equipment item rated
 * another way (a rated point, or a Cv or Kv), the fluid made custom.
 */
function lapseNotes(before: Project, next: Project): string[] {
	const notes: string[] = [];
	const users = (test: (o: Override) => boolean) =>
		scenariosOf(next)
			.filter((s) => overridesOf(s).some(test))
			.map((s) => s.name);
	for (const component of next.components) {
		const old = componentById(before, component.id);
		if (old?.type !== 'pump' || component.type !== 'pump' || !old.control || component.control)
			continue;
		const names = users(
			(o) =>
				o.kind === 'component' && o.componentId === component.id && o.field === 'control.setpoint'
		);
		if (names.length) {
			notes.push(
				`The flow setpoint changes of ${component.name} in ${namesList(names)} no longer apply: it has no flow control now. They apply again if flow control is added back.`
			);
		}
	}
	for (const component of next.components) {
		const old = componentById(before, component.id);
		if (old?.type !== 'equipment' || component.type !== 'equipment') continue;
		const wasPoint = old.rating.kind === 'point';
		if (wasPoint === (component.rating.kind === 'point')) continue;
		const names = users(
			(o) =>
				o.kind === 'component' &&
				o.componentId === component.id &&
				(wasPoint ? o.field !== 'rating.value' : o.field === 'rating.value') &&
				o.field.startsWith('rating.')
		);
		if (names.length) {
			const now =
				component.rating.kind === 'point'
					? 'a pressure drop at a flow'
					: `a ${component.rating.kind}`;
			const then = wasPoint ? 'a pressure drop at a flow' : `a ${old.rating.kind}`;
			notes.push(
				`The rating value changes of ${component.name} in ${namesList(names)} no longer apply: it is rated by ${now} now. They apply again if it is rated by ${then}.`
			);
		}
	}
	if (before.fluid.kind === 'builtin' && next.fluid.kind === 'custom') {
		const names = users((o) => o.kind === 'project' && o.field === 'fluid.temperature');
		if (names.length) {
			notes.push(
				`The fluid temperature changes in ${namesList(names)} no longer apply: a custom fluid's properties do not depend on its temperature.`
			);
		}
	}
	return notes;
}

/**
 * A note when an insertion splits a pipe that a scenario resizes: the new short pipe after the
 * inserted component has the base case's size in that scenario.
 */
function splitNotes(before: Project, next: Project): string[] {
	const notes: string[] = [];
	for (const connection of next.connections) {
		if (connectionById(before, connection.id)) continue;
		const inserted = connection.fromComponentId;
		if (componentById(before, inserted)) continue;
		const kept = next.connections.find(
			(c) => c.toComponentId === inserted && connectionById(before, c.id)
		);
		if (!kept) continue;
		const last = kept.piping.pipes.length - 1;
		const names = scenariosOf(next)
			.filter((s) =>
				overridesOf(s).some(
					(o) =>
						o.kind === 'pipe' &&
						o.connectionId === kept.id &&
						o.pipeIndex === last &&
						o.field === 'spec'
				)
			)
			.map((s) => s.name);
		if (names.length) {
			const name = componentById(next, inserted)?.name ?? inserted;
			notes.push(
				`The new pipe after ${name} has the base case's size in ${namesList(names)}, which changes the pipe it was split from.`
			);
		}
	}
	return notes;
}

