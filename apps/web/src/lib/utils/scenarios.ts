/** Where a change's value lives in the project JSON, when it applies. */
interface Resolved {
	state: 'applied';
	/** The object that holds the value (a component, a pipe, the fluid's holder). */
	target: JsonObject;
	entry: OverrideField;
}

interface Ignored {
	state: Exclude<OverrideState, 'applied'>;
	/** Why it is ignored, in the app's words. */
	message: string;
}

const PIPE_FIELD_NAMES: Readonly<Record<string, string>> = {
	spec: 'size and material',
	length: 'length'
};

function walk(value: unknown, path: readonly string[]): unknown {
	let node = value;
	for (const key of path) {
		if (!isRecord(node)) return undefined;
		node = node[key];
	}
	return node;
}

/**
 * Whether `holder` can hold a value of `schema`: a fluid must be of that fluid schema (a custom
 * fluid has no temperature to change); any other holder, such as a pump's control, must exist.
 */
function holderMatches(holder: unknown, schema: string): boolean {
	if (!isRecord(holder)) return false;
	const fluid = 'type' in holder ? null : fluidSchemaName(holder.kind);
	return fluid === null || fluid === schema;
}

function resolve(project: Project, override: Override): Resolved | Ignored {
	if (override.kind === 'component') {
		const component = componentById(project, override.componentId);
		if (!component) {
			return { state: 'orphaned', message: `${override.componentId} was deleted` };
		}
		const entry = componentOverrideFields(component)[override.field];
		const label = fieldLabelFor(component, override.field).toLowerCase();
		if (!entry) {
			return {
				state: 'not_applicable',
				message: `${component.name} (${kindLabel(component).toLowerCase()}) has no ${label}`
			};
		}
		const holder = entry.path.length > 1 ? walk(component, entry.path.slice(0, -1)) : component;
		if (!holderMatches(holder, entry.schema)) {
			return {
				state: 'not_applicable',
				message:
					override.field === 'control.setpoint'
						? `${component.name} has no flow control`
						: `${component.name} has no ${label}`
			};
		}
		return { state: 'applied', target: component as unknown as JsonObject, entry };
	}
	if (override.kind === 'pipe') {
		const connection = connectionById(project, override.connectionId);
		const entry = pipeOverrideFields()[override.field];
		if (!connection) {
			return { state: 'orphaned', message: `connection ${override.connectionId} was deleted` };
		}
		const pipes = connection.piping.pipes;
		const pipe = pipes[override.pipeIndex];
		if (!pipe) {
			const count = `${pipes.length} pipe${pipes.length === 1 ? '' : 's'}`;
			return {
				state: 'orphaned',
				message: `connection ${connection.id} has ${count}, no pipe ${override.pipeIndex + 1}`
			};
		}
		if (!entry) {
			return { state: 'not_applicable', message: `a pipe has no ${override.field}` };
		}
		return { state: 'applied', target: pipe as unknown as JsonObject, entry };
	}
	const entry = projectOverrideFields()[override.field];
	if (!entry) return { state: 'not_applicable', message: `the project has no ${override.field}` };
	const holder = walk(project, entry.path.slice(0, -1));
	if (entry.path.length > 1 && !holderMatches(holder, entry.schema)) {
		return {
			state: 'not_applicable',
			message: 'the fluid is a custom fluid, whose properties do not depend on its temperature'
		};
	}
	return { state: 'applied', target: project as unknown as JsonObject, entry };
}

/** A pipe-spec value is an object of the spec's keys only (the API rejects any other key). */
export function validSpec(
	value: unknown,
	entry: OverrideField = pipeOverrideFields().spec!
): boolean {
	return isRecord(value) && Object.keys(value).every((key) => entry.keys.includes(key));
}

/** Write a change's value into `target` (a group, a pipe's spec, replaces all its keys). */
function write(target: JsonObject, entry: OverrideField, value: unknown): void {
	const copy = structuredClone(value);
	if (entry.keys.length) {
		for (const key of entry.keys) delete target[key];
		Object.assign(target, copy as JsonObject);
		return;
	}
	const holder = walk(target, entry.path.slice(0, -1));
	if (isRecord(holder)) holder[entry.path[entry.path.length - 1] as string] = copy;
}

/** The value a change sets on `target`, read from it: JSON, absent optional values as null. */
function read(target: JsonObject, entry: OverrideField): unknown {
	if (entry.keys.length) {
		const spec: JsonObject = {};
		for (const key of entry.keys) if (target[key] != null) spec[key] = target[key];
		return spec;
	}
	return walk(target, entry.path) ?? null;
}

/** How one change of a scenario is used in its case. */
export interface ChangeState {
	index: number;
	override: Override;
	state: OverrideState;
	/** Why it no longer applies ('' when it applies). */
	message: string;
	/** The value is not a pipe spec (keys other than the spec's): ignored here, rejected by the API. */
	invalid?: true;
}

export interface AppliedScenario {
	/** The scenario applied (undefined for the base, or an unknown id). */
	scenario: Scenario | undefined;
	/** The effective project: the base with the scenario's changes, without `scenarios`. */
	project: Project;
	changes: ChangeState[];
}

/**
 * The project a case is: the base project with the scenario's changes written at their targets
 * (as the API's apply_scenario does), without `scenarios`. Changes are resolved against the base
 * (a scenario changes values only), so their order does not matter. Values are written as they
 * are; whether they are valid is checked like any project (scenario-problems.ts) and by the API.
 */
export function applyScenario(project: Project, scenarioId: CaseId): AppliedScenario {
	const data = structuredClone(project) as Project;
	delete data.scenarios;
	const scenario = findScenario(project, scenarioId);
	if (!scenario) return { scenario, project: data, changes: [] };
	const states: ChangeState[] = [];
	const writes: { target: JsonObject; entry: OverrideField; value: unknown }[] = [];
	overridesOf(scenario).forEach((override, index) => {
		const resolved = resolve(data, override);
		if (resolved.state !== 'applied') {
			states.push({ index, override, state: resolved.state, message: resolved.message });
			return;
		}
		if (resolved.entry.keys.length && !validSpec(override.value, resolved.entry)) {
			states.push({ index, override, state: 'applied', message: '', invalid: true });
			return;
		}
		states.push({ index, override, state: 'applied', message: '' });
		writes.push({ target: resolved.target, entry: resolved.entry, value: override.value });
	});
	for (const w of writes) write(w.target, w.entry, w.value);
	return { scenario, project: data, changes: states };
}

/**
 * The project of a case for editing and display: the base (itself) or the base with the
 * scenario's changes, carrying the base's scenarios, so the case's forms show its values.
 */
export function caseProject(project: Project, caseId: CaseId): Project {
	if (caseId === null || !findScenario(project, caseId)) return project;
	const applied = applyScenario(project, caseId).project;
	return project.scenarios ? { ...applied, scenarios: project.scenarios } : applied;
}

/**
 * How each change of a scenario is used in its case (as applyScenario reports, without building
 * the case's project): cheap enough for every render.
 */
export function changeStates(project: Project, scenarioId: string): ChangeState[] {
	return overridesOf(findScenario(project, scenarioId)).map((override, index) => {
		const resolved = resolve(project, override);
		if (resolved.state !== 'applied') {
			return { index, override, state: resolved.state, message: resolved.message };
		}
		return resolved.entry.keys.length && !validSpec(override.value, resolved.entry)
			? { index, override, state: 'applied', message: '', invalid: true }
			: { index, override, state: 'applied', message: '' };
	});
}

/** The changes of a scenario that no longer apply (orphaned or not applicable). */
export function lapsedChanges(project: Project, scenarioId: string): ChangeState[] {
	return changeStates(project, scenarioId).filter((c) => c.state !== 'applied');
}

/**
 * The value of `field` on `target` in `project` (JSON; an absent optional value is null; a
 * pipe's spec as the keys it has), or undefined when the target does not have it.
 */
export function valueOf(project: Project, target: ChangeTarget, field: string): unknown {
	const resolved = resolve(project, makeOverride(target, field, null));
	return resolved.state === 'applied' ? read(resolved.target, resolved.entry) : undefined;
}

/**
 * Write `value` as `field` of `target` in `project` (a draft: changed in place), where `valueOf`
 * reads it: the inverse of valueOf (a group's keys, a pipe's spec, are replaced together). Returns
 * false, changing nothing, when the target does not have the value (deleted, or not applicable).
 */
export function setValue(project: Project, target: ChangeTarget, field: string, value: unknown) {
	const resolved = resolve(project, makeOverride(target, field, value));
	if (resolved.state !== 'applied') return false;
	write(resolved.target, resolved.entry, value);
	return true;
}

/** The scenario's change of `field` on `target`, if it has one. */
export function findChange(
	scenario: Scenario | undefined,
	target: ChangeTarget,
	field: string
): { index: number; override: Override } | null {
	const list = overridesOf(scenario);
	const index = list.findIndex((o) => changes(o, target, field));
	return index === -1 ? null : { index, override: list[index] as Override };
}

/** The scenario with the change of `field` on `target` removed (the base value applies). */
export function withoutChange(scenario: Scenario, target: ChangeTarget, field: string): Scenario {
	return {
		...scenario,
		overrides: overridesOf(scenario).filter((o) => !changes(o, target, field))
	};
}

/** The scenario with `override` set: it replaces a change of the same value, in its place. */
export function withChange(scenario: Scenario, override: Override): Scenario {
	const list = [...overridesOf(scenario)];
	const target = changeTarget(override);
	const index = list.findIndex((o) => changes(o, target, override.field));
	if (index === -1) list.push(override);
	else list[index] = override;
	return { ...scenario, overrides: list };
}

/** Staleness key of a case: the base's hydraulic fingerprint, plus a scenario's changes. */
export function caseKey(project: Project, caseId: CaseId, fingerprint: string): string | null {
	if (caseId === null) return fingerprint;
	const scenario = findScenario(project, caseId);
	return scenario ? `${fingerprint}\u0000${canonicalJson(overridesOf(scenario))}` : null;
}

