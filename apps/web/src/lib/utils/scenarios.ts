/** An edit made in a scenario that applies to every case (labels only). */
type SharedEdit =
	| { kind: 'componentName'; componentId: string; name: string }
	| { kind: 'projectName'; name: string }
	| { kind: 'description'; description: string | undefined }
	| { kind: 'units'; units: Project['settings']['units'] };

interface RawChange {
	target: ChangeTarget;
	field: string;
	value: unknown;
}

interface CaseDiff {
	refused: boolean;
	changes: RawChange[];
	shared: SharedEdit[];
}

function without(record: object, keys: readonly string[]): JsonObject {
	const copy: JsonObject = { ...(record as JsonObject) };
	for (const key of keys) delete copy[key];
	return copy;
}

/** A copy of `value` without the leaf of each path (the values a scenario may change). */
function locked(
	value: object,
	paths: readonly (readonly string[])[],
	also: readonly string[] = []
) {
	const copy = structuredClone(value) as JsonObject;
	for (const key of also) delete copy[key];
	for (const path of paths) {
		const holder = walk(copy, path.slice(0, -1));
		if (isRecord(holder)) delete holder[path[path.length - 1] as string];
	}
	return canonicalJson(copy);
}

function entryPaths(entries: Readonly<Record<string, OverrideField>>): string[][] {
	return Object.values(entries).flatMap((e) =>
		e.keys.length ? e.keys.map((k) => [k]) : [[...e.path]]
	);
}

function diffComponents(before: Component, after: Component, diff: CaseDiff): void {
	if (before.id !== after.id || componentSchemaName(before) !== componentSchemaName(after)) {
		diff.refused = true;
		return;
	}
	const entries = componentOverrideFields(before);
	if (
		locked(before, entryPaths(entries), ['name']) !== locked(after, entryPaths(entries), ['name'])
	) {
		diff.refused = true;
		return;
	}
	const target: ChangeTarget = { kind: 'component', componentId: before.id };
	for (const [field, entry] of Object.entries(entries)) {
		const b = read(before as unknown as JsonObject, entry);
		const a = read(after as unknown as JsonObject, entry);
		if (!sameValue(a, b)) diff.changes.push({ target, field, value: a });
	}
	if (before.name !== after.name) {
		diff.shared.push({ kind: 'componentName', componentId: before.id, name: after.name });
	}
}

function diffConnections(before: PipeConnection, after: PipeConnection, diff: CaseDiff): void {
	const outline = (c: PipeConnection) =>
		canonicalJson({ ...c, piping: { fittings: c.piping.fittings, pipes: c.piping.pipes.length } });
	if (outline(before) !== outline(after)) {
		diff.refused = true;
		return;
	}
	const entries = pipeOverrideFields();
	before.piping.pipes.forEach((pipe, pipeIndex) => {
		const next = after.piping.pipes[pipeIndex] as PipeDefinition;
		if (locked(pipe, entryPaths(entries)) !== locked(next, entryPaths(entries))) {
			diff.refused = true;
			return;
		}
		const target: ChangeTarget = { kind: 'pipe', connectionId: before.id, pipeIndex };
		for (const [field, entry] of Object.entries(entries)) {
			const b = read(pipe as unknown as JsonObject, entry);
			const a = read(next as unknown as JsonObject, entry);
			if (!sameValue(a, b)) diff.changes.push({ target, field, value: a });
		}
	});
}

/** What an edit of a case's project changed: scenario values, shared labels, or refused. */
function diffCase(before: Project, after: Project): CaseDiff {
	const diff: CaseDiff = { refused: false, changes: [], shared: [] };
	const sameIds = (a: readonly { id: string }[], b: readonly { id: string }[]) =>
		a.length === b.length && a.every((x, i) => x.id === b[i]?.id);
	if (
		!sameIds(before.components, after.components) ||
		!sameIds(before.connections, after.connections)
	) {
		return { ...diff, refused: true };
	}
	before.components.forEach((c, i) => diffComponents(c, after.components[i] as Component, diff));
	before.connections.forEach((c, i) =>
		diffConnections(c, after.connections[i] as PipeConnection, diff)
	);
	const outline = (p: Project) =>
		canonicalJson({
			...without(p, ['components', 'connections', 'fluid', 'metadata', 'settings']),
			metadata: without(p.metadata, ['name', 'description', 'modified']),
			settings: without(p.settings, ['units'])
		});
	if (outline(before) !== outline(after)) diff.refused = true;
	if (diff.refused) return diff;
	if (before.metadata.name !== after.metadata.name) {
		diff.shared.push({ kind: 'projectName', name: after.metadata.name });
	}
	if ((before.metadata.description ?? null) !== (after.metadata.description ?? null)) {
		diff.shared.push({ kind: 'description', description: after.metadata.description ?? undefined });
	}
	if (!sameValue(before.settings.units, after.settings.units)) {
		diff.shared.push({ kind: 'units', units: after.settings.units });
	}
	if (!sameValue(before.fluid, after.fluid)) {
		diff.changes.push({ target: { kind: 'project' }, field: 'fluid', value: after.fluid });
	}
	return diff;
}

function withoutTemperature(fluid: FluidDefinition): JsonObject {
	return without(fluid, ['temperature']);
}

/**
 * The scenario's changes after `raw` (values as the edited case has them): each upserted in its
 * place, or removed where it equals the base value again. The fluid is one `fluid.temperature`
 * change while only a built-in fluid's temperature differs from the base, else one whole-fluid
 * change (which a temperature edit then updates).
 */
function nextOverrides(scenario: Scenario, raw: readonly RawChange[], base: Project): Override[] {
	let list = [...overridesOf(scenario)];
	const set = (target: ChangeTarget, field: string, value: unknown | undefined) => {
		const index = list.findIndex((o) => changes(o, target, field));
		const override = value === undefined ? null : makeOverride(target, field, value);
		if (index === -1) {
			if (override) list.push(override);
		} else if (override) list[index] = override;
		else list = list.filter((_, i) => i !== index);
	};
	for (const change of raw) {
		if (change.target.kind === 'project' && change.field === 'fluid') {
			const fluid = change.value as FluidDefinition;
			const project = { kind: 'project' } as const;
			const whole = list.some((o) => o.kind === 'project' && o.field === 'fluid');
			if (sameValue(fluid, base.fluid)) {
				set(project, 'fluid', undefined);
				set(project, 'fluid.temperature', undefined);
			} else if (
				!whole &&
				fluid.kind === 'builtin' &&
				base.fluid.kind === 'builtin' &&
				sameValue(withoutTemperature(fluid), withoutTemperature(base.fluid))
			) {
				set(project, 'fluid.temperature', fluid.temperature);
			} else {
				// The whole fluid replaces a temperature change (a value and a part of it never both).
				const index = list.findIndex(
					(o) => o.kind === 'project' && o.field === 'fluid.temperature'
				);
				if (index !== -1) list[index] = makeOverride(project, 'fluid', fluid);
				else set(project, 'fluid', fluid);
			}
			continue;
		}
		const baseValue = valueOf(base, change.target, change.field);
		set(change.target, change.field, sameValue(change.value, baseValue) ? undefined : change.value);
	}
	return list;
}

function applyShared(draft: Project, shared: readonly SharedEdit[]): void {
	for (const edit of shared) {
		if (edit.kind === 'componentName') {
			const component = draft.components.find((c) => c.id === edit.componentId);
			if (component) component.name = edit.name;
		} else if (edit.kind === 'projectName') {
			draft.metadata.name = edit.name;
		} else if (edit.kind === 'description') {
			if (edit.description === undefined) delete draft.metadata.description;
			else draft.metadata.description = edit.description;
		} else {
			draft.settings.units = { ...edit.units };
		}
	}
}

export type ScenarioEdit =
	| {
			ok: true;
			/** Apply the edit to a draft of the base project (one undo step). */
			apply: (draft: Project) => void;
	  }
	| { ok: false; reason: 'refused' | 'limit' | 'failed'; message: string };

export const LIMIT_MESSAGE = `A scenario holds at most ${MAX_CHANGES} changes.`;

/**
 * An edit made while scenario `scenarioId` is shown: `change` edits a copy of the case's project
 * (as every form edits the project), and the difference is sorted out. Values on the allow-list
 * become the scenario's changes (a value typed back to the base value removes its change); names,
 * the project name and description and the display units are shared by every case and go to the
 * base; anything else (topology, a locked value) refuses the whole edit.
 */
export function scenarioEdit(
	base: Project,
	scenarioId: string,
	change: (draft: Project) => Project | void
): ScenarioEdit {
	const scenario = findScenario(base, scenarioId);
	if (!scenario) return { ok: false, reason: 'failed', message: 'the scenario no longer exists.' };
	const before = caseProject(base, scenarioId);
	let after: Project;
	try {
		const draft = structuredClone(before);
		after = change(draft) ?? draft;
	} catch (error) {
		return {
			ok: false,
			reason: 'failed',
			message: error instanceof Error ? error.message : String(error)
		};
	}
	const diff = diffCase(before, after);
	if (diff.refused) return { ok: false, reason: 'refused', message: 'refused' };
	const overrides = nextOverrides(scenario, diff.changes, base);
	if (overrides.length > MAX_CHANGES && overrides.length > overridesOf(scenario).length) {
		return { ok: false, reason: 'limit', message: LIMIT_MESSAGE };
	}
	return {
		ok: true,
		apply: (draft) => {
			const target = draft.scenarios?.find((s) => s.id === scenarioId);
			if (target) target.overrides = overrides;
			applyShared(draft, diff.shared);
		}
	};
}

