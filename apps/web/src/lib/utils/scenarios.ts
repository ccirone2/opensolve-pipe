export function scenariosOf(project: Project): readonly Scenario[] {
	return project.scenarios ?? [];
}

export function findScenario(project: Project, id: string | null): Scenario | undefined {
	return id === null ? undefined : scenariosOf(project).find((s) => s.id === id);
}

export function overridesOf(scenario: Scenario | undefined): readonly Override[] {
	return scenario?.overrides ?? [];
}

/** The first free scenario id: S1, S2, ... (scenario ids are a namespace of their own). */
export function newScenarioId(project: Project): string {
	const used = new Set(scenariosOf(project).map((s) => s.id));
	for (let n = 1; ; n++) if (!used.has(`S${n}`)) return `S${n}`;
}

/** "Scenario n" for a new scenario: n is the number of its id, else the next free number. */
export function newScenarioName(project: Project, id: string): string {
	const number = /^S(\d+)$/.exec(id)?.[1];
	if (number) return `Scenario ${number}`;
	return `Scenario ${scenariosOf(project).length + 1}`;
}

/** "Winter (copy)", cut to the name limit. */
export function copyName(name: string): string {
	const suffix = ' (copy)';
	return name.length + suffix.length <= SCENARIO_NAME_LIMIT
		? `${name}${suffix}`
		: `${name.slice(0, SCENARIO_NAME_LIMIT - suffix.length)}${suffix}`;
}

/** The project with its scenarios replaced; an empty list removes the key (links stay as before). */
export function withScenarios(project: Project, scenarios: readonly Scenario[]): Project {
	const next: Project = { ...project };
	if (scenarios.length) next.scenarios = [...scenarios];
	else delete next.scenarios;
	return next;
}

/** Ids of components and connections the scenarios' changes name (deleted ones included). */
export function changeTargetIds(project: Project): Set<string> {
	const ids = new Set<string>();
	for (const scenario of scenariosOf(project)) {
		for (const o of overridesOf(scenario)) {
			if (o.kind === 'component') ids.add(o.componentId);
			if (o.kind === 'pipe') ids.add(o.connectionId);
		}
	}
	return ids;
}

